#!/usr/bin/env bash
# studio releases: ONE version, ONE changelog, ONE tag, ONE GitHub Release.
#
# Two separate stages (the Captain, 2026-10-21):
#
#   dev --promotion PR (merge commit)--> main     main = FINISHED FEATURES.
#       full checks + Reviewer on the diff        Nothing deploys, nothing
#                                                 uploads on a push to main.
#   main --release PR (version + changelog)--> tag vX.Y.Z on main
#                                                 The TAG ships: the two
#                                                 sites (deploy), BOTH
#                                                 TestFlight uploads (Signal,
#                                                 Session), the REAPER suites,
#                                                 the desktop installers and
#                                                 the one GitHub Release.
#
# Production is the latest `v*` tag. Features pile up on main between
# releases; a release is cut when the Captain/Commander/DevOps decides.
#
# The version lives in ONE place, `[workspace.package] version` in the
# root Cargo.toml. Every crate that says `version.workspace = true` follows
# it, and that includes both iOS app crates (apps/signal/desktop,
# apps/session/desktop), so Signal and Session can never differ: Signal
# and Session are the same build, and a change to one almost always
# touches the other. There are no per-app tags, branches or changelogs.
# The `v<version>` tag drives BOTH TestFlight uploads (signal-ios.yml,
# session-ios.yml): the marketing version of each is the tag's version, and
# each writes its build number into the same Release's notes. Nothing else
# uploads to TestFlight. Versions start at 0.1.0 and only the patch moves
# (0.1.9 -> 0.1.10, never rolling over) unless the Captain or Commander
# calls a minor/major. The plugins' tags are not covered here.
#
# The changelog is GENERATED by git-cliff (cliff.toml) from the commit
# subjects between the last tag and the release commit on main. PRs into
# dev are squash-merged with a conventional-commit title, so each PR is one
# changelog line; commits pushed to dev directly land under "Changes". Edit
# the commit, not the file.
#
#   scripts/release.sh version            the current version
#   scripts/release.sh plan               what is live, what main holds, what
#                                          waits on dev, the next release
#   scripts/release.sh promote            PR dev -> main (merge commit): the
#                                          "finished features" stage
#   scripts/release.sh prepare [BUMP]     cut release/v<next> from origin/main:
#                                          bump + changelog + release commit
#                                          (BUMP: patch (default), minor,
#                                          major, auto or X.Y.Z; minor/major
#                                          only when the Captain or
#                                          Commander calls one)
#   scripts/release.sh pr                 push the release (or hotfix) branch
#                                          and open its PR into main
#   scripts/release.sh tag [VERSION]      after the release PR merged: tag
#                                          v<VERSION> on main (this is what
#                                          ships), then back-merge
#   scripts/release.sh backmerge          PR main -> dev (merge commit,
#                                          auto-merge); a no-op when dev has
#                                          everything main has
#   scripts/release.sh hotfix NAME        hotfix/NAME from the latest tag
#   scripts/release.sh notes [VERSION]    one version's changelog section
#   scripts/release.sh guard              CI: is this PR into main sound?
#   scripts/release.sh release-only       CI (checks): is this PR only a
#                                          release commit? (exit 0 = yes)
#   scripts/release.sh tag-guard          CI (deploy): is this tag a release
#                                          on main?
#   scripts/release.sh publish [TAG]      CI: the GitHub Release for the tag
#   scripts/release.sh ios-resolve APP TAG
#                                         CI (<app>-ios.yml): refuse a tag that
#                                          is not vX.Y.Z, whose app crate
#                                          version differs, that has no
#                                          changelog section or is not on main;
#                                          print the marketing version
#   scripts/release.sh ios-release TAG    CI: make sure the tag's GitHub Release
#                                          exists (idempotent, safe to run from
#                                          both iOS workflows at once)
#   scripts/release.sh ios-record APP TAG MARKETING BUILD [RUN_URL]
#                                         CI: after the TestFlight upload, write
#                                          the marketing version + build number
#                                          into the release notes (one line per
#                                          app; safe to run concurrently)
#
# See docs/agents/release-workflow.md for the whole procedure.
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"
REPO="${GITHUB_REPOSITORY:-FastTrackStudios/studio}"
INTEGRATION_BRANCH="${INTEGRATION_BRANCH:-dev}"
PRODUCTION_BRANCH="${PRODUCTION_BRANCH:-main}"

die() { echo "release: $*" >&2; exit 1; }
note() { echo "release: $*" >&2; }

# git-cliff from PATH, else from nixpkgs (it is not in the dev shell, and
# adding it there would make every flake.lock bump an infra change).
cliff() {
    if command -v git-cliff >/dev/null 2>&1; then
        git-cliff "$@"
    elif command -v nix >/dev/null 2>&1; then
        nix run --accept-flake-config nixpkgs#git-cliff -- "$@"
    else
        die "git-cliff not found (and no nix to fetch it)"
    fi
}

# `[workspace.package] version` of Cargo.toml at a revision (default: the
# working tree).
version_at() {
    local src
    if [ -n "${1:-}" ]; then src="$(git show "$1:Cargo.toml")"; else src="$(cat Cargo.toml)"; fi
    printf '%s\n' "$src" \
        | sed -n '/^\[workspace\.package\]/,/^\[/{s/^version *= *"\([^"]*\)".*/\1/p;}' \
        | head -1
}

is_semver() { [[ "$1" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; }

# The release commit's subject for a version, as an ERE (a squash merge
# may append " (#N)").
release_subject_re() { # <version>
    printf '^chore\\(release\\): v%s( \\(#[0-9]+\\))?$' "${1//./\\.}"
}

# true when $1 > $2 (both X.Y.Z)
gt() { [ "$1" != "$2" ] && [ "$(printf '%s\n%s\n' "$1" "$2" | sort -V | tail -1)" = "$1" ]; }

bump() { # bump <X.Y.Z> <major|minor|patch>
    local IFS=.; read -r ma mi pa <<<"$1"
    case "$2" in
        major) echo "$((ma + 1)).0.0" ;;
        minor) echo "$ma.$((mi + 1)).0" ;;
        patch) echo "$ma.$mi.$((pa + 1))" ;;
        *) die "unknown bump '$2'" ;;
    esac
}

# The newest product tag reachable from HEAD.
last_tag() {
    git tag --list 'v[0-9]*' --merged "${1:-HEAD}" --sort=-v:refname \
        | grep -E '^v[0-9]+\.[0-9]+\.[0-9]+$' | head -1 || true
}

# ── the iOS apps (Signal, Session) ───────────────────────────────────────
# They are not released on their own: they are built from the one `v<version>`
# tag. Their crates follow the workspace version; the helpers below read
# that back so the guard and the TestFlight gate can prove it.
IOS_APPS="signal session"

ios_check() {
    case "${1:-}" in signal|session) ;; *) die "unknown iOS app '${1:-}' (signal or session)" ;; esac
}
ios_manifest() { case "$1" in signal) echo apps/signal/desktop/Cargo.toml ;; session) echo apps/session/desktop/Cargo.toml ;; esac; }
ios_title() { case "$1" in signal) echo Signal ;; session) echo Session ;; esac; }
ios_bundle_id() { echo "app.fasttrackstudio.$1"; }

# The version an app crate resolves to at a revision (default: working
# tree): the workspace version when it says `version.workspace = true`, else
# its own literal `[package] version`. Empty when neither is there.
crate_version_at() { # <app> [rev]
    local f src pkg; f="$(ios_manifest "$1")"
    if [ -n "${2:-}" ]; then src="$(git show "$2:$f" 2>/dev/null || true)"; else src="$(cat "$f" 2>/dev/null || true)"; fi
    pkg="$(printf '%s\n' "$src" | sed -n '/^\[package\]/,/^\[/p')"
    if grep -Eq '^version(\.workspace *= *true| *= *\{ *workspace *= *true *\})' <<<"$pkg"; then
        version_at "${2:-}"
    else
        printf '%s\n' "$pkg" | sed -n 's/^version *= *"\([^"]*\)".*/\1/p' | head -1
    fi
}

# Git dependencies whose locked commit moved in a range — behaviour can
# arrive without a line of this repo's source changing (architect,
# keyflow, the vendor repo, …). Release notes carry the list.
git_deps_moved() { # <from> <to>
    [ -n "$1" ] || return 0
    git diff -U0 "$1" "$2" -- Cargo.lock \
        | grep -E '^\+source = "git\+' \
        | sed -E 's/^\+source = "git\+([^?#"]+).*/\1/' | sort -u || true
}

cmd_version() { version_at; }

cmd_notes() { # [VERSION]
    local v="${1:-$(version_at)}" f=CHANGELOG.md
    [ -f "$f" ] || { note "no $f"; return 1; }
    awk -v want="## [$v]" '
        index($0, want) == 1 { on = 1; next }
        on && /^## \[/ { exit }
        on { print }
    ' "$f" | sed -e '/./,$!d' # drop leading blank lines
}

# The very first release: no `v*` tag is reachable from <rev>, and <rev>'s
# CHANGELOG.md has no section for <version>, which already IS <rev>'s
# workspace version (the repo starts at 0.1.0 and v0.1.0 is cut without a
# bump). Every later release must be greater than main's version.
first_release() { # <rev> <version>
    [ -z "$(last_tag "$1")" ] || return 1
    [ "$(version_at "$1")" = "$2" ] || return 1
    ! changelog_has "$1" "$2"
}

# `git rev-list --count --no-merges A..B`, tolerant of a missing A.
count_between() {
    if [ -n "${1:-}" ]; then git rev-list --count --no-merges "$1..$2"; else git rev-list --count --no-merges "$2"; fi 2>/dev/null || echo 0
}

# true when <rev>:CHANGELOG.md has a `## [<version>]` section. (A variable,
# not `git show | grep -q`: under pipefail grep -q exits at the first match,
# the writer dies of SIGPIPE, and that reads as "no match" on a big file.)
changelog_has() { # <rev> <version>
    local c; c="$(git show "$1:CHANGELOG.md" 2>/dev/null)" || return 1
    grep -q "^## \[$2\]" <<<"$c"
}


cmd_plan() {
    git fetch --quiet --tags origin "$INTEGRATION_BRANCH" "$PRODUCTION_BRANCH" 2>/dev/null || true
    local ref="origin/$PRODUCTION_BRANCH" cur tag next a cv
    cur="$(version_at "$ref")"; tag="$(last_tag "$ref")"
    next="$(bump "$cur" patch)"
    echo "production (latest v* tag):  ${tag:-none}"
    echo "version on $PRODUCTION_BRANCH:             $cur"
    for a in $IOS_APPS; do
        cv="$(crate_version_at "$a" "$ref")"
        echo "$a crate version:    ${cv:-?}$([ "$cv" = "$cur" ] || echo '   <-- differs from the workspace version')"
    done
    echo "finished, not yet released:  $(count_between "$tag" "$ref") commits on $PRODUCTION_BRANCH since ${tag:-the start}"
    echo "waiting on $INTEGRATION_BRANCH (not promoted): $(count_between "$ref" "origin/$INTEGRATION_BRANCH") commits (just release-promote)"
    echo "next release:                $next (patch, the default; minor/major only when the Captain or Commander calls one)"
    echo "                             one tag v$next and one GitHub Release for Signal + Session; both TestFlight uploads come from it"
    echo
    echo "── unreleased changelog ($PRODUCTION_BRANCH, ${tag:+$tag..}$PRODUCTION_BRANCH) ──"
    cliff --strip header --tag "v$next" ${tag:+"$tag..$ref"} || true
    if [ -n "$tag" ]; then
        local d; d="$(git_deps_moved "$tag" "$ref")"
        echo "── git dependencies moved since $tag ──"
        echo "${d:-none}"
    fi
}

# Stage 1: dev -> main, "finished features". A merge commit; nothing
# ships on the push. Opens (or prints) the promotion PR with the commit
# list and moved git deps as its body.
cmd_promote() {
    local ahead existing body merged from
    git fetch --quiet --tags origin "$INTEGRATION_BRANCH" "$PRODUCTION_BRANCH"
    ahead="$(count_between "origin/$PRODUCTION_BRANCH" "origin/$INTEGRATION_BRANCH")"
    [ "$ahead" -gt 0 ] || die "$INTEGRATION_BRANCH has nothing $PRODUCTION_BRANCH lacks: nothing to promote"
    merged="$(git merge-tree --write-tree "origin/$PRODUCTION_BRANCH" "origin/$INTEGRATION_BRANCH" 2>/dev/null | head -1 || true)"
    [ "$merged" = "$(git rev-parse "origin/$INTEGRATION_BRANCH^{tree}")" ] \
        || die "$PRODUCTION_BRANCH has content $INTEGRATION_BRANCH lacks (a release commit or a hotfix). Back-merge first: just release-backmerge, let it merge, then promote."
    existing="$(gh pr list --repo "$REPO" --head "$INTEGRATION_BRANCH" --base "$PRODUCTION_BRANCH" --state open --json url --jq '.[0].url' 2>/dev/null || true)"
    if [ -n "$existing" ]; then note "the promotion PR is already open: $existing"; return 0; fi
    from="$(last_tag "origin/$PRODUCTION_BRANCH")"
    body="$(mktemp)"
    {
        echo "Promote \`$INTEGRATION_BRANCH\` → \`$PRODUCTION_BRANCH\`: **$ahead** change(s) that were verified on \`$INTEGRATION_BRANCH\` and are now FINISHED FEATURES waiting for the next release."
        echo
        echo "- **Nothing ships on merge**: no deploy, no TestFlight, no installers. Production is the latest \`v*\` tag; a release is cut from \`$PRODUCTION_BRANCH\` later (\`just release-prepare\`)."
        echo "- Full \`checks\` and the release guard run on this PR; the **Reviewer** agent reviews this diff (blocking / should-fix / nit) and posts the review as a comment on this PR before merge."
        echo "- Merge with **Create a merge commit** (never squash or rebase)."
        echo
        echo "### Changes"
        git log --no-merges --format='- %s' "origin/$PRODUCTION_BRANCH..origin/$INTEGRATION_BRANCH"
        echo
        local d; d="$(git_deps_moved "origin/$PRODUCTION_BRANCH" "origin/$INTEGRATION_BRANCH")"
        if [ -n "$d" ]; then
            echo "### Git dependencies moved"
            # shellcheck disable=SC2086 # $d is a word list
            printf -- '- %s\n' $d
        fi
        [ -n "$from" ] && echo && echo "Production is at \`$from\`."
    } > "$body"
    gh pr create --repo "$REPO" --base "$PRODUCTION_BRANCH" --head "$INTEGRATION_BRANCH" \
        --title "Promote $INTEGRATION_BRANCH to $PRODUCTION_BRANCH ($ahead changes)" --body-file "$body"
    rm -f "$body"
}

# Stage 2: cut release/v<next> from origin/main (the finished features).
cmd_prepare() {
    # Patch by default, whatever the commits say: minor and major bumps
    # are a decision (the Captain or Commander calls them), not something
    # a feat commit triggers. `auto` asks git-cliff instead.
    local want="${1:-patch}" cur next branch tag
    [ -z "$(git status --porcelain --untracked-files=no)" ] || die "working tree is dirty"
    git fetch --quiet --tags origin "$PRODUCTION_BRANCH"
    cur="$(version_at "origin/$PRODUCTION_BRANCH")"
    is_semver "$cur" || die "Cargo.toml version '$cur' is not X.Y.Z"
    tag="$(last_tag "origin/$PRODUCTION_BRANCH")"
    # A release commit already on main but never tagged: finish that one.
    # (Main carries a changelog section for its own version, and no tag
    # names it. This also holds before the very first tag exists.)
    if ! git rev-parse -q --verify "refs/tags/v$cur" >/dev/null && changelog_has "origin/$PRODUCTION_BRANCH" "$cur"; then
        die "origin/$PRODUCTION_BRANCH is at $cur, which has a changelog section but no tag v$cur (latest tag: ${tag:-none}): an earlier release was merged and not tagged. Finish it: just release-tag"
    fi
    if [ -n "$tag" ] && [ "$(count_between "$tag" "origin/$PRODUCTION_BRANCH")" -eq 0 ]; then
        die "nothing to release: $PRODUCTION_BRANCH has no commits since $tag (promote finished features first: just release-promote)"
    fi

    branch="release/pending"
    git switch --quiet -C "$branch" "origin/$PRODUCTION_BRANCH"

    case "$want" in
        auto) next="$(cliff --bumped-version | sed 's/^v//')"
              # Nothing conventional enough to bump: default to a minor
              # while 0.x (pre-1.0, a release is a feature drop).
              { [ -z "$next" ] || ! gt "$next" "$cur"; } && next="$(bump "$cur" minor)" ;;
        major|minor|patch) next="$(bump "$cur" "$want")" ;;
        *) is_semver "$want" || die "BUMP must be auto, major, minor, patch or X.Y.Z"
           next="$want" ;;
    esac
    if [ "$next" = "$cur" ] && first_release "origin/$PRODUCTION_BRANCH" "$next"; then
        note "first release: v$next is main's own version, so the release commit adds the changelog only"
    else
        gt "$next" "$cur" || die "next version $next is not greater than $cur"
    fi
    git rev-parse -q --verify "refs/tags/v$next" >/dev/null && die "tag v$next already exists"
    if git ls-remote --exit-code --heads origin "release/v$next" >/dev/null 2>&1; then
        git switch --quiet --detach "origin/$PRODUCTION_BRANCH"
        git branch --quiet -D "$branch"
        die "release/v$next is already open on origin. Finish it (merge, then just release-tag) or close its PR and delete the branch to re-cut."
    fi

    git branch --quiet -M "$branch" "release/v$next"
    note "cutting release/v$next (was $cur) from origin/$PRODUCTION_BRANCH $(git rev-parse --short "origin/$PRODUCTION_BRANCH")"
    release_commit "$cur" "$next"
    cat >&2 <<EOT

Next:
  1. Read CHANGELOG.md's [$next] section. A wrong line is a wrong commit
     subject on dev: note it for next time; never hand-edit the generated file.
  2. just release-pr   — pushes release/v$next and opens it -> $PRODUCTION_BRANCH.
     Only the release guard runs in full: the content was checked at its
     promotion (a release commit changes the version and the changelog only).
  3. Merge it with a merge commit, then: just release-tag — tags v$next on
     $PRODUCTION_BRANCH. THE TAG SHIPS: both sites, BOTH TestFlight uploads
     (Signal and Session, marketing version $next), REAPER, the Release.
  If $PRODUCTION_BRANCH moves before the merge (another promotion), close the PR,
  delete the branch and cut again: it takes a minute.
EOT
}

# Bump the version (Cargo.toml: the one line both iOS crates follow),
# Cargo.lock, regenerate the changelog, commit `chore(release): v<next>` on
# the current branch.
release_commit() { # <cur> <next>
    local cur="$1" next="$2"
    if [ "$cur" != "$next" ]; then
        # The one version line.
        sed -i.bak "/^\[workspace\.package\]/,/^\[/s/^version *= *\"$cur\"/version = \"$next\"/" Cargo.toml
        rm -f Cargo.toml.bak
        [ "$(version_at)" = "$next" ] || die "failed to rewrite [workspace.package] version"

        # Workspace members' entries in the lockfile follow; nothing else may
        # move. --offline first: a version bump needs no index.
        cargo update --workspace --offline 2>/dev/null || cargo update --workspace
    fi

    changelog_write "$next"

    git add Cargo.toml Cargo.lock CHANGELOG.md
    git commit --quiet -m "chore(release): v$next"
    note "committed: $(git log -1 --format='%h %s')"
}

# Write <version>'s section into CHANGELOG.md (replacing it if present),
# above every older section, which stay as released. The section holds
# exactly the commits reachable from HEAD and not from the last release
# tag — a git RANGE. git-cliff's own whole-history walk files commits
# under tags by date, and with release branches that is wrong: a card
# merged into dev while v0.2.4 was out would be listed under 0.2.4,
# which never shipped it. One section covers both apps.
changelog_write() { # <version>
    local v="$1" from sec file=CHANGELOG.md
    from="$(last_tag HEAD)"
    sec="$(mktemp)"
    # The first release creates the file with cliff.toml's header.
    [ -f "$file" ] || cliff --strip footer --tag "v$v" ${from:+"$from..HEAD"} \
        | sed '/^## \[/,$d' > "$file"
    cliff --tag "v$v" --strip all ${from:+"$from..HEAD"} > "$sec"
    grep -q "^## \[$v\]" "$sec" \
        || die "git-cliff produced no [$v] section: nothing to release since ${from:-the first commit}?"
    awk -v want="## [$v]" -v sec="$sec" '
        function emit(   n, i, l, buf) {
            n = 0; while ((getline l < sec) > 0) buf[++n] = l
            while (n > 0 && buf[n] == "") n--          # no trailing blanks
            for (i = 1; i <= n; i++) print buf[i]
            print ""; done = 1
        }
        index($0, want) == 1 { skip = 1; if (!done) emit(); next }
        skip && /^## \[/ { skip = 0 }
        skip { next }
        /^## \[/ && !done { emit() }
        { print }
        END { if (!done) emit() }
    ' "$file" > "$sec.new"
    mv "$sec.new" "$file"
    rm -f "$sec"
    grep -q "^## \[$v\]" "$file" || die "$file has no [$v] section"
}


# A hotfix: hotfix/<name> from the latest tag (what production runs). Fix,
# commit (conventional subject), then `just release-pr`: the PR goes into
# main with the full checks, like a promotion. Then cut the patch release
# as usual (prepare, pr, tag). main may hold finished features that were
# promoted since the tag: they ship with the hotfix, because promoted means
# verified.
cmd_hotfix() {
    local name="${1:-}" tag
    [ -n "$name" ] || die "usage: release.sh hotfix <name>   (creates hotfix/<name> from the latest tag)"
    [[ "$name" =~ ^[A-Za-z0-9._-]+$ ]] || die "hotfix name '$name' must be [A-Za-z0-9._-]"
    [ -z "$(git status --porcelain --untracked-files=no)" ] || die "working tree is dirty"
    git fetch --quiet --tags origin "$PRODUCTION_BRANCH"
    tag="$(last_tag "origin/$PRODUCTION_BRANCH")"
    [ -n "$tag" ] || die "no v* tag on origin/$PRODUCTION_BRANCH to branch from"
    git switch --quiet -c "hotfix/$name" "refs/tags/$tag"
    cat >&2 <<EOT
hotfix/$name is at $tag (production). Next:
  1. Fix it; commit with a conventional subject (fix(scope): ...); run just ci.
  2. just release-pr — pushes hotfix/$name, opens it -> $PRODUCTION_BRANCH; the full checks and the guard run.
  3. Merge with a merge commit, then cut the patch release: just release-prepare, release-pr, merge, release-tag.
     (finished features promoted since $tag ship with it)
EOT
}

# Push the current release/v* (or hotfix/*) branch and open its PR into
# main, with the changelog and moved git deps as the body.
cmd_pr() {
    local ref v body kind existing tag
    ref="$(git rev-parse --abbrev-ref HEAD)"
    case "$ref" in
        release/v*) kind=Release ;;
        hotfix/*) kind=Hotfix ;;
        *) die "run this on the release/v* (or hotfix/*) branch (on '$ref'); just release-prepare / release-hotfix makes one" ;;
    esac
    [ -z "$(git status --porcelain --untracked-files=no)" ] || die "working tree is dirty"
    v="$(version_at)"; tag="v$v"
    if [ "$kind" = Release ]; then
        [[ "$(git log -1 --format=%s)" =~ $(release_subject_re "$v") ]] \
            || die "the head is not the release commit for $tag (just release-prepare)"
    fi
    git fetch --quiet --tags origin "$PRODUCTION_BRANCH"
    git push --quiet origin "HEAD:refs/heads/$ref"
    existing="$(gh pr list --repo "$REPO" --head "$ref" --base "$PRODUCTION_BRANCH" --state open --json url --jq '.[0].url' 2>/dev/null || true)"
    if [ -n "$existing" ]; then
        note "pushed; the PR is already open: $existing"; return 0
    fi
    local from; from="$(last_tag "origin/$PRODUCTION_BRANCH")"
    body="$(mktemp)"
    if [ "$kind" = Release ]; then
        {
            echo "Release **$tag**: \`$ref\` → \`$PRODUCTION_BRANCH\` (source \`$(git rev-parse --short HEAD)\`). One commit: the version bump and the changelog."
            echo
            echo "Everything in it was checked and reviewed when it was promoted into \`$PRODUCTION_BRANCH\`; this PR changes only \`Cargo.toml\`, \`Cargo.lock\` and \`CHANGELOG.md\` (the release guard proves it), so the heavy checks are skipped here."
            echo "Merge with **Create a merge commit**. Merging ships nothing. **The tag does:** after the merge run \`just release-tag\` (tags \`$tag\` on \`$PRODUCTION_BRANCH\`) → both sites deploy, BOTH TestFlight uploads (\`signal-ios\`, \`session-ios\`, marketing version **$v**, one build number each written into the Release notes), the REAPER suites, the one GitHub Release."
            echo
            local d; d="$(git_deps_moved "$from" HEAD)"
            if [ -n "$d" ]; then
                echo "### Git dependencies moved"
                # shellcheck disable=SC2086 # $d is a word list
                printf -- '- %s\n' $d
                echo
            fi
            echo "### Changelog"
            cmd_notes "$v"
        } > "$body"
        gh pr create --repo "$REPO" --base "$PRODUCTION_BRANCH" --head "$ref" \
            --title "Release $tag" --body-file "$body"
    else
        {
            echo "Hotfix \`$ref\` → \`$PRODUCTION_BRANCH\` (branched from \`${from:-?}\`, production). Full checks and the release guard run here."
            echo
            echo "Merge with **Create a merge commit**. Merging ships nothing: cut the patch release next (\`just release-prepare\`, \`release-pr\`, \`release-tag\`) and back-merge into \`$INTEGRATION_BRANCH\`."
            echo
            echo "### Changes"
            git log --no-merges --format='- %s' "origin/$PRODUCTION_BRANCH..HEAD"
        } > "$body"
        gh pr create --repo "$REPO" --base "$PRODUCTION_BRANCH" --head "$ref" \
            --title "Hotfix: ${ref#hotfix/}" --body-file "$body"
    fi
    rm -f "$body"
}

# After the release PR merged: tag v<version> on main. The TAG is the
# release: it starts the deploy, BOTH TestFlight uploads, the REAPER suites
# and the GitHub Release. The tag goes on the release commit's merge into
# main (the oldest first-parent commit of main carrying that version), not
# on a later promotion. Pushing as a GitHub App (fts-forge) or a person
# starts the workflows; a tag pushed with a workflow's GITHUB_TOKEN would not.
cmd_tag() {
    local v="${1:-}" target="" c prev
    git fetch --quiet --tags origin "$PRODUCTION_BRANCH"
    [ -n "$v" ] || v="$(version_at "origin/$PRODUCTION_BRANCH")"
    v="${v#v}"
    is_semver "$v" || die "version '$v' is not X.Y.Z"
    if git rev-parse -q --verify "refs/tags/v$v" >/dev/null; then
        die "tag v$v already exists ($(git rev-parse --short "v$v^{commit}")). Never move a tag; a bad release is superseded by the next."
    fi
    # The release commit's merge into main is the OLDEST first-parent commit
    # of main that carries version $v AND its changelog section (a later
    # promotion keeps both). Walking by the changelog section also finds the
    # first release, where the version did not change.
    local found_edge=0
    for c in $(git rev-list --first-parent -n 400 "origin/$PRODUCTION_BRANCH"); do
        if [ "$(version_at "$c")" = "$v" ] && changelog_has "$c" "$v"; then target="$c"; else found_edge=1; break; fi
    done
    [ "$found_edge" = 1 ] || [ -z "$target" ] || die "all of main's last 400 first-parent commits carry version $v with its changelog section: cannot find the release commit"
    [ -n "$target" ] || die "no commit on origin/$PRODUCTION_BRANCH carries version $v with a changelog section: has the release PR merged?"
    changelog_has "$target" "$v" \
        || die "CHANGELOG.md at $(git rev-parse --short "$target") has no [$v] section: not a release commit"
    prev="$(last_tag "$target^")"
    if [ -n "$prev" ]; then
        gt "$v" "${prev#v}" || die "v$v is not greater than the previous release $prev"
    fi
    note "tagging v$v at $(git rev-parse --short "$target") on $PRODUCTION_BRANCH (previous: ${prev:-none}). This ships: sites, Signal + Session TestFlight, REAPER, the Release."
    # An annotated tag needs a committer identity; a bot checkout may have none.
    local ident=()
    git config user.email >/dev/null 2>&1 || [ -n "${GIT_COMMITTER_EMAIL:-}" ] \
        || ident=(-c "user.name=fts-forge[bot]" -c "user.email=fts-forge[bot]@users.noreply.github.com")
    git ${ident[@]+"${ident[@]}"} tag -a "v$v" "$target" -m "studio $v"
    git push --quiet origin "refs/tags/v$v"
    note "pushed v$v: deploy, signal-ios, session-ios, reaper and the Release start from the tag"
    cmd_backmerge
}

# After a release (or hotfix) reached main: bring main back into dev with
# a merge commit, so dev carries the bump, the changelog and any hotfix,
# and the next promotion reproduces dev's tree. A no-op when dev already
# has everything main has (after a plain promotion main only gains the
# merge commit, whose tree is dev's).
cmd_backmerge() {
    local v sha branch existing merged
    git fetch --quiet --tags origin "$INTEGRATION_BRANCH" "$PRODUCTION_BRANCH"
    merged="$(git merge-tree --write-tree "origin/$INTEGRATION_BRANCH" "origin/$PRODUCTION_BRANCH" 2>/dev/null | head -1 || true)"
    if [ "$merged" = "$(git rev-parse "origin/$INTEGRATION_BRANCH^{tree}")" ]; then
        note "origin/$INTEGRATION_BRANCH already has all of origin/$PRODUCTION_BRANCH's content — nothing to back-merge"; return 0
    fi
    sha="$(git rev-parse "origin/$PRODUCTION_BRANCH")"
    v="$(version_at "origin/$PRODUCTION_BRANCH")"
    # One branch per main tip: a hotfix back-merge at the same version must
    # not push a different sha onto an old backmerge/vX branch (non-ff).
    branch="backmerge/v$v-$(git rev-parse --short "$sha")"
    existing="$(gh pr list --repo "$REPO" --head "$branch" --base "$INTEGRATION_BRANCH" --state open --json url --jq '.[0].url' 2>/dev/null || true)"
    if [ -z "$existing" ]; then
        # A branch, not main itself, as the PR head: a conflict (a card that
        # touched a workspace member's Cargo.lock entry next to its version
        # line) is resolved by merging dev into this branch, never on main.
        git push --quiet origin "$sha:refs/heads/$branch"
        existing="$(gh pr create --repo "$REPO" --base "$INTEGRATION_BRANCH" --head "$branch" \
            --title "chore(release): back-merge v$v into $INTEGRATION_BRANCH" \
            --body "Brings \`$PRODUCTION_BRANCH\` ($(git rev-parse --short "$sha"), v$v) back into \`$INTEGRATION_BRANCH\`: the version bump, the changelog and any hotfix. **Merge commit**, never squash: the next promotion must reproduce dev's tree. Opened by \`just release-backmerge\`." | tail -1)"
    fi
    local subj="Merge $PRODUCTION_BRANCH into $INTEGRATION_BRANCH after v$v"
    gh pr merge "$existing" --repo "$REPO" --merge --auto --subject "$subj" \
        || gh pr merge "$existing" --repo "$REPO" --merge --subject "$subj" \
        || note "could not enable auto-merge; merge $existing with a merge commit once its title check is green"
    note "back-merge: $existing"
    if ! git merge-tree --write-tree "origin/$INTEGRATION_BRANCH" "$sha" >/dev/null 2>&1; then
        note "it CONFLICTS: git switch $branch && git merge origin/$INTEGRATION_BRANCH, resolve (Cargo.lock: cargo update --workspace), push $branch"
    fi
}

# Is the diff base..head ONLY a release commit's: Cargo.toml's version
# line, the workspace members' version lines in Cargo.lock, CHANGELOG.md?
# (a version bump cannot change what the checks tested)
release_diff_only() { # <base> <head>
    # No `... | grep -q` pipelines: under pipefail, grep -q exits at the first
    # match and the writer dies of SIGPIPE, which reads as "no match" on a
    # big diff. Capture into a variable, then test it.
    local base="$1" head="$2" f out vb vh
    while read -r f; do
        case "$f" in Cargo.toml|Cargo.lock|CHANGELOG.md) ;; *) return 1 ;; esac
    done < <(git diff --name-only "$base" "$head")
    # Cargo.toml: exactly the one [workspace.package] version line changes.
    vb="$(version_at "$base")"; vh="$(version_at "$head")"
    [ "$vb" != "$vh" ] || [ -z "$(git diff "$base" "$head" -- Cargo.toml)" ] || return 1
    out="$(git diff -U0 "$base" "$head" -- Cargo.toml | grep -E '^[+-]' | grep -vE '^(\+\+\+|---)' || true)"
    if [ -n "$out" ]; then
        [ "$(printf '%s\n' "$out" | wc -l)" -eq 2 ] || return 1
        [ "$(printf '%s\n' "$out" | grep -cE '^-version *= *"[0-9]+\.[0-9]+\.[0-9]+"[[:space:]]*$' || true)" -eq 1 ] || return 1
        [ "$(printf '%s\n' "$out" | grep -cE '^\+version *= *"[0-9]+\.[0-9]+\.[0-9]+"[[:space:]]*$' || true)" -eq 1 ] || return 1
    fi
    # Cargo.lock: only version lines.
    out="$(git diff -U0 "$base" "$head" -- Cargo.lock | grep -E '^[+-]' | grep -vE '^(\+\+\+|---)' | grep -vE '^[+-]version = "[^"]*"$' || true)"
    [ -z "$out" ] || return 1
    return 0
}

# CI (checks.yml plan): exit 0 when this PR is only a release commit on
# release/v*, whose content was checked when it was promoted.
cmd_release_only() {
    local base="${BASE_SHA:?}" head="${HEAD_SHA:?}" ref="${HEAD_REF:?}"
    case "$ref" in release/v*) ;; *) return 1 ;; esac
    git merge-base --is-ancestor "$base" "$head" || return 1
    [ "$(git rev-list --count "$base..$head")" = 1 ] || return 1
    [[ "$(git log -1 --format=%s "$head")" =~ $(release_subject_re "$(version_at "$head")") ]] || return 1
    release_diff_only "$base" "$head"
}

# CI, on a pull request into main. Three kinds of head:
#   dev            a promotion: finished features. The merge must reproduce
#                  dev's tree (so dev has everything main has), and the
#                  version is untouched (versions move only on main).
#   release/vX.Y.Z ONE release commit on top of main: version + changelog.
#   hotfix/*       a fix branched from the production tag.
cmd_guard() {
    local base="${BASE_SHA:?}" head="${HEAD_SHA:?}" ref="${HEAD_REF:?}"
    local v vb merged subject ok=1 kind tag a cv
    fail() { echo "::error::$*"; ok=0; }

    # Bootstrap: main still takes ordinary PRs until the release flow has
    # reached it, including the one that adds this guard. That is true
    # while main has no scripts/release.sh (whether or not `dev` exists
    # yet), or while there is no `dev` at all.
    if ! git cat-file -e "$base:scripts/release.sh" 2>/dev/null; then
        echo "::notice::main has no scripts/release.sh yet — this PR introduces the release flow; release guard not enforced"
        return 0
    fi
    if ! git ls-remote --exit-code --heads origin "$INTEGRATION_BRANCH" >/dev/null 2>&1; then
        echo "::notice::no '$INTEGRATION_BRANCH' branch yet — release guard not enforced"
        return 0
    fi
    git fetch --quiet --tags origin \
        "+refs/heads/$INTEGRATION_BRANCH:refs/remotes/origin/$INTEGRATION_BRANCH" 2>/dev/null || true

    v="$(version_at "$head")"; vb="$(version_at "$base")"; tag="v$v"
    is_semver "$v" || fail "Cargo.toml version '$v' is not X.Y.Z"
    merged="$(git merge-tree --write-tree "$base" "$head" 2>/dev/null | head -1 || true)"

    case "$ref" in
        "$INTEGRATION_BRANCH")
            kind=promotion
            [ "$(count_between "$base" "$head")" -gt 0 ] || fail "nothing to promote: $ref has no commits main lacks"
            [ "$v" = "$vb" ] || fail "$ref carries version $v but main is at $vb: versions are bumped on main by just release-prepare, never on $INTEGRATION_BRANCH"
            [ "$merged" = "$(git rev-parse "$head^{tree}")" ] \
                || fail "merging would not reproduce $ref's tree: main has content $ref lacks (a release commit or hotfix). Back-merge first: just release-backmerge, let it merge, re-run."
            ;;
        release/v*)
            kind=release
            [ "$ref" = "release/v$v" ] || fail "branch '$ref' carries version '$v'; a release branch is named release/v<its version> (just release-prepare)"
            if [ "$v" = "$vb" ] && first_release "$base" "$v"; then
                echo "::notice::first release: v$v is main's own version (no v* tag yet), the release commit adds the changelog only"
            else
                gt "$v" "$vb" || fail "version $v is not greater than main's $vb — cut the release with just release-prepare"
            fi
            git rev-parse -q --verify "refs/tags/$tag" >/dev/null && fail "tag $tag already exists"
            changelog_has "$head" "$v" || fail "CHANGELOG.md at the head has no [$v] section"
            subject="$(git log -1 --format=%s "$head")"
            [[ "$subject" =~ $(release_subject_re "$v") ]] \
                || fail "the head commit must be the release commit 'chore(release): $tag' (it is '$subject')"
            git merge-base --is-ancestor "$base" "$head" \
                || fail "main ($(git rev-parse --short "$base")) is not in $ref: main moved since the cut. Close this PR, delete the branch and cut again (just release-prepare)"
            [ "$(git rev-list --count "$base..$head")" = 1 ] \
                || fail "a release branch is exactly one commit on top of main (the release commit); this one has $(git rev-list --count "$base..$head"). Features are promoted from $INTEGRATION_BRANCH, not shipped in the release PR."
            release_diff_only "$base" "$head" \
                || fail "the release commit may change only the version line in Cargo.toml / Cargo.lock and CHANGELOG.md"
            # One version for the whole studio: Signal and Session follow the
            # workspace version (version.workspace = true), so they cannot differ.
            for a in $IOS_APPS; do
                cv="$(crate_version_at "$a" "$head")"
                [ "$cv" = "$v" ] \
                    || fail "$(ios_manifest "$a") resolves to version '${cv:-none}' but the release is $v: both apps take [workspace.package] version (version.workspace = true)"
            done
            ;;
        hotfix/*)
            kind=hotfix
            [ "$v" = "$vb" ] || fail "a hotfix does not bump the version ($v vs main's $vb): the patch release is cut afterwards from main"
            [ "$(count_between "$base" "$head")" -gt 0 ] || fail "nothing in $ref that main lacks"
            git merge-tree --write-tree "$base" "$head" >/dev/null 2>&1 || fail "$ref conflicts with main: merge origin/main into it"
            ;;
        *) kind=other
           fail "PRs into main come from $INTEGRATION_BRANCH (a promotion), release/vX.Y.Z (just release-prepare) or hotfix/*, not '$ref'. Other PRs target '$INTEGRATION_BRANCH'." ;;
    esac

    {
        echo "### Release guard: $kind ($ref → main)"
        echo "- version: $vb → $v (Signal and Session share it: one tag, one Release)"
        echo "- head: \`$(git rev-parse --short "$head")\` $(git log -1 --format=%s "$head")"
        echo "- commits main lacks: $(count_between "$base" "$head")"
        echo "- merge tree identical to head tree: $([ "$merged" = "$(git rev-parse "$head^{tree}")" ] && echo yes || echo no)"
        local d; d="$(git_deps_moved "$(last_tag "$base")" "$head" | paste -sd, -)"
        echo "- git deps moved since last release: ${d:-none}"
        echo "- merging ships nothing; production changes only when a v* tag is pushed (sites, signal-ios + session-ios TestFlight, REAPER, the Release)"
    } >> "${GITHUB_STEP_SUMMARY:-/dev/stderr}"
    [ "$ok" = 1 ] || exit 1
    echo "release guard: ok ($kind)"
}

# CI, first step of the deploy: the tag that started this run must be a
# release commit on main. Stops a stray `v*` tag (on a card branch, on a
# commit with another version) from reaching production.
cmd_tag_guard() {
    local ref="${GITHUB_REF:-}" tag v ok=1 a cv
    fail() { echo "::error::$*"; ok=0; }
    case "$ref" in
        refs/tags/v*) tag="${ref#refs/tags/}" ;;
        *) die "this runs from a v* tag (ref is '${ref:-none}'). Production changes only by tag: just release-tag, or dispatch this workflow with the tag as its ref." ;;
    esac
    v="$(version_at HEAD)"
    [ "$tag" = "v$v" ] || fail "tag $tag but Cargo.toml says $v"
    for a in $IOS_APPS; do
        cv="$(crate_version_at "$a")"
        [ "$cv" = "$v" ] || fail "$(ios_manifest "$a") resolves to version '${cv:-none}' but the tag is $tag"
    done
    git fetch --quiet origin "+refs/heads/$PRODUCTION_BRANCH:refs/remotes/origin/$PRODUCTION_BRANCH" 2>/dev/null || true
    git merge-base --is-ancestor HEAD "origin/$PRODUCTION_BRANCH" \
        || fail "$tag ($(git rev-parse --short HEAD)) is not in $PRODUCTION_BRANCH's history: releases are tagged on $PRODUCTION_BRANCH"
    grep -q "^## \[$v\]" CHANGELOG.md 2>/dev/null || fail "CHANGELOG.md has no [$v] section: $tag is not a release commit"
    [ "$ok" = 1 ] || exit 1
    echo "tag guard: ok ($tag at $(git rev-parse --short HEAD), on $PRODUCTION_BRANCH)"
}


# The block both TestFlight uploads fill in, kept at the end of the
# release notes between these markers: one line per app.
TF_BEGIN='<!-- testflight:begin -->'
TF_END='<!-- testflight:end -->'

# The app's line in the block of a release body (empty when there is none).
tf_app_line() { # <body> <app>
    printf '%s\n' "$1" | sed -n "\\#$TF_BEGIN#,\\#$TF_END#p" | grep -F -- "- $(ios_title "$2") (" | head -1 || true
}

tf_pending_line() { # <app>
    echo "- $(ios_title "$1") (\`$(ios_bundle_id "$1")\`): pending — \`$1-ios\` builds this tag and writes its build number here"
}

# The whole block: this app's line is <newline> (when given), every other
# app's is the one already in <body>, else pending.
tf_render() { # <tag> <version> <body> [<app> <newline>]
    local a l
    echo "$TF_BEGIN"
    echo "### iOS TestFlight"
    echo "Marketing version **$2** (CFBundleShortVersionString) == this release, \`$1\`, for Signal and Session alike. One line per app, its latest upload."
    for a in $IOS_APPS; do
        if [ "$a" = "${4:-}" ]; then
            echo "${5:-}"
        else
            l="$(tf_app_line "$3" "$a")"
            echo "${l:-$(tf_pending_line "$a")}"
        fi
    done
    echo "$TF_END"
}


# CI, on the tag (and from the iOS workflows, and by hand). The tag already
# exists (cmd_tag pushed it); this attaches the GitHub Release with the
# changelog section, moved git deps and the TestFlight block. Idempotent.
# With no argument the tag is the ref of the run, else HEAD's workspace
# version. signal-ios and session-ios both ask for the Release of a tag,
# and one of them is first.
publish_release() { # [tag]
    local v tag="${1:-}" target prev notes
    if [ -z "$tag" ]; then
        case "${GITHUB_REF:-}" in refs/tags/v*) tag="${GITHUB_REF#refs/tags/}" ;; esac
    fi
    if [ -n "$tag" ]; then v="${tag#v}"; else v="$(version_at HEAD)"; tag="v$v"; fi
    is_semver "$v" || die "version '$v' is not X.Y.Z"
    if [ "$(version_at HEAD)" != "$v" ] && [ -z "${1:-}" ]; then
        die "tag $tag but Cargo.toml says $(version_at HEAD)"
    fi
    if gh release view "$tag" --repo "$REPO" >/dev/null 2>&1; then
        note "release $tag already exists — nothing to do"; return 0
    fi
    if ! grep -q "^## \[$v\]" CHANGELOG.md 2>/dev/null; then
        note "CHANGELOG.md has no [$v] section — not a release commit, nothing to publish"; return 0
    fi
    git rev-parse -q --verify "refs/tags/$tag" >/dev/null || die "no tag $tag: tag first (just release-tag)"
    target="$(git rev-parse "$tag^{commit}")"
    prev="$(last_tag "$target^")"

    notes="$(mktemp)"
    {
        cmd_notes "$v" || true
        local d; d="$(git_deps_moved "$prev" "$target")"
        if [ -n "$d" ]; then
            echo
            echo "### Git dependencies moved"
            # shellcheck disable=SC2086 # $d is a word list
            printf -- '- %s\n' $d
        fi
        echo
        echo "---"
        echo "Tag \`$tag\` at \`$(git rev-parse --short "$target")\` on main (site images \`sha-$(git rev-parse --short "$target")\`)."
        [ -n "$prev" ] && echo "Full diff: https://github.com/$REPO/compare/$prev...$tag"
        echo
        tf_render "$tag" "$v" ""
    } > "$notes"
    [ -s "$notes" ] || die "no release notes for $v"

    if ! gh release create "$tag" --repo "$REPO" --verify-tag \
        --title "studio $v" --notes-file "$notes" --latest; then
        gh release view "$tag" --repo "$REPO" >/dev/null 2>&1 \
            || die "could not create the GitHub Release for $tag"
        note "release $tag was created meanwhile — nothing to do"; rm -f "$notes"; release_dedupe "$tag"; return 0
    fi
    rm -f "$notes"
    release_dedupe "$tag"
    note "published https://github.com/$REPO/releases/tag/$tag"
}

# `publish` and both ios-release steps start together on a tag, and
# `gh release view` + `gh release create` is not atomic: GitHub lets three
# creators each make a Release for one tag (v0.1.1 got three, and editing any
# of them then fails with 422 "tag_name already_exists"). Whoever created one
# keeps the lowest id and deletes the rest (the tag stays); concurrent callers
# converge on the same survivor.
release_dedupe() { # <tag>
    local tag="$1" ids keep id
    ids="$(gh api --paginate "repos/$REPO/releases" --jq ".[] | select(.tag_name == \"$tag\") | .id" 2>/dev/null | sort -n)" || return 0
    keep="$(head -1 <<<"$ids")"
    [ -n "$keep" ] || return 0
    for id in $ids; do
        [ "$id" = "$keep" ] && continue
        gh api -X DELETE "repos/$REPO/releases/$id" >/dev/null 2>&1 \
            && note "removed the duplicate Release $id of $tag (kept $keep)"
    done
    return 0
}

cmd_publish() { publish_release "$@"; }


# CI, first job of <app>-ios.yml, run in a checkout of the tag. TestFlight
# ships exactly the tag: refuse a tag that is not vX.Y.Z, an app crate
# (or the workspace) whose version is not the tag's, a tag without its
# changelog section, a commit that is not in main. Prints the marketing
# version.
cmd_ios_resolve() { # <app> <tag>
    local app="${1:-}" tag="${2:-}" v cv wv sha re
    ios_check "$app"
    re='^v[0-9]+\.[0-9]+\.[0-9]+$'
    [[ "$tag" =~ $re ]] || die "tag '$tag' does not match $re: TestFlight uploads only from a release tag"
    v="${tag#v}"
    cv="$(crate_version_at "$app")"
    [ "$cv" = "$v" ] \
        || die "$(ios_manifest "$app") says version '${cv:-none}' but the tag is $tag ($v): the marketing version is the tag's, so the crate must carry it (version.workspace = true, released with just release-prepare)"
    wv="$(version_at)"
    [ "$wv" = "$v" ] \
        || die "[workspace.package] version is '$wv' but the tag is $tag ($v): one version for Signal and Session"
    grep -q "^## \[$v\]" CHANGELOG.md 2>/dev/null \
        || die "CHANGELOG.md has no [$v] section: $tag is not a release commit"
    sha="$(git rev-parse HEAD)"
    if git rev-parse -q --verify "refs/tags/$tag" >/dev/null; then
        [ "$(git rev-parse "$tag^{commit}")" = "$sha" ] || die "this checkout ($sha) is not $tag"
    fi
    git fetch --quiet origin "$PRODUCTION_BRANCH"
    git merge-base --is-ancestor "$sha" "origin/$PRODUCTION_BRANCH" \
        || die "$tag ($(git rev-parse --short "$sha")) is not in origin/$PRODUCTION_BRANCH: only a release that reached $PRODUCTION_BRANCH goes to TestFlight"
    note "$tag: marketing version $v, commit $(git rev-parse --short "$sha"), bundle $(ios_bundle_id "$app")"
    if [ -n "${GITHUB_OUTPUT:-}" ]; then
        { echo "version=$v"; echo "sha=$sha"; echo "tag=$tag"; } >> "$GITHUB_OUTPUT"
    fi
    echo "$v"
}

cmd_ios_release() { # <tag>
    local tag="${1:-}"
    [[ "$tag" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "usage: ios-release vX.Y.Z"
    publish_release "$tag"
}

# The app's line once its build is uploaded; earlier builds of the same
# version (a re-run) stay listed at its end.
ios_record_line() { # <app> <build> <run-url> <prior line>
    local app="$1" build="$2" run="$3" prior="$4" cur old list="" line
    cur="$(sed -n 's/^.*: build \([0-9][0-9]*\),.*$/\1/p' <<<"$prior")"
    old="$(sed -n 's/^.*(earlier builds: \([0-9, ]*\))$/\1/p' <<<"$prior")"
    if [ "$cur" = "$build" ]; then echo "$prior"; return 0; fi
    [ -z "$cur" ] || list="$cur"
    [ -z "$old" ] || list="${list:+$list, }$old"
    line="- $(ios_title "$app") (\`$(ios_bundle_id "$app")\`): build $build, $(date -u +%FT%TZ)${run:+, [run]($run)}"
    [ -z "$list" ] || line="$line (earlier builds: $list)"
    echo "$line"
}

# CI, last job of <app>-ios.yml: write what was uploaded into the release
# notes, so the GitHub Release and the TestFlight build name each other.
# Signal and Session record into the SAME Release at about the same time,
# and `gh release edit` replaces the whole body, so each run re-reads the
# notes before editing and, after a short settle, checks its own line
# survived; if the other run's edit overwrote it, it goes round again.
cmd_ios_record() { # <app> <tag> <marketing> <build> [run-url]
    local app="${1:-}" tag="${2:-}" mv="${3:-}" build="${4:-}" run="${5:-}"
    local body prior line keep out tries=0 max="${RECORD_TRIES:-6}"
    ios_check "$app"
    [ "$tag" = "v$mv" ] || die "marketing version '$mv' is not the version of tag '$tag'"
    [[ "$build" =~ ^[0-9]+$ ]] || die "build number '$build' is not a number"
    release_dedupe "$tag"   # an edit of a tag with several Releases is a 422
    while :; do
        tries=$((tries + 1))
        body="$(gh release view "$tag" --repo "$REPO" --json body --jq .body)" \
            || die "no GitHub Release for $tag (TestFlight needs one: ios-release)"
        prior="$(tf_app_line "$body" "$app")"
        if ! grep -Fq -- "): build $build," <<<"$prior"; then
            line="$(ios_record_line "$app" "$build" "$run" "$prior")"
            keep="$(printf '%s\n' "$body" | sed "\\#$TF_BEGIN#,\\#$TF_END#d" | sed -e :a -e '/^\n*$/{$d;N;ba' -e '}')"
            out="$(mktemp)"
            {
                printf '%s\n\n' "$keep"
                tf_render "$tag" "$mv" "$body" "$app" "$line"
            } > "$out"
            gh release edit "$tag" --repo "$REPO" --notes-file "$out"
            rm -f "$out"
        fi
        sleep "${RECORD_SETTLE:-4}"
        body="$(gh release view "$tag" --repo "$REPO" --json body --jq .body)" \
            || die "no GitHub Release for $tag"
        if grep -Fq -- "): build $build," <<<"$(tf_app_line "$body" "$app")"; then
            note "recorded on $tag: $app marketing $mv, build $build"
            return 0
        fi
        [ "$tries" -lt "$max" ] || die "could not record $app build $build on $tag after $tries tries: the notes kept being overwritten"
        note "the notes of $tag changed under $app's edit; trying again ($tries/$max)"
        sleep "$((RANDOM % 3 + 1))"
    done
}


#!/usr/bin/env bash
# studio releases: one version, one changelog, one tag.
#
# The version lives in ONE place, `[workspace.package] version` in the
# root Cargo.toml (every crate that says `version.workspace = true`
# follows it). The `v<version>` git tag and its GitHub Release are cut
# when the release reaches main.
#
# Signal and Session (the iOS apps) are released PER APP, at versions of
# their own: the `[package] version` of the app crate (apps/<app>/desktop/
# Cargo.toml), the tag `<app>-v<version>` (signal-v0.1.3), the changelog
# apps/<app>/CHANGELOG.md. They start at 0.1.0 and only the patch moves
# (0.1.9 -> 0.1.10, never rolling over). The app's GitHub Release is made
# when its release reaches main, and ONLY that tag uploads a TestFlight
# build, whose marketing version is the tag's version (signal-ios.yml,
# session-ios.yml). Nothing else uploads to TestFlight. The plugins' tags
# are not covered here.
#
# The changelog is GENERATED by git-cliff (cliff.toml) from the commit
# subjects on `dev`. PRs into dev are squash-merged with a
# conventional-commit title, so each PR is one changelog line; commits
# pushed to dev directly land under "Changes". Edit the commit, not the
# file.
#
# A release is a BRANCH, `release/v<next>`, cut from dev's head. Dev never
# freezes: cards keep landing while the release branch is checked,
# merged into main, deployed and tagged. Afterwards main is back-merged
# into dev, which is how dev gets the bump, the changelog and any fix
# made on the release branch.
#
#   scripts/release.sh version            the current version
#   scripts/release.sh plan [APP]         what the next release would be
#   scripts/release.sh prepare [APP] [BUMP]
#                                         cut release/v<next> (or, for APP =
#                                          signal|session, release/<app>-v<next>)
#                                          from origin/dev: bump + changelog +
#                                          release commit (BUMP: patch
#                                          (default), minor, major, auto or
#                                          X.Y.Z; minor/major only when the
#                                          Captain or Commander calls one; an
#                                          app has no `auto`; an app's first
#                                          release is its baseline, 0.1.0)
#   scripts/release.sh pr                 push the release (or hotfix) branch
#                                          and open its PR into main
#   scripts/release.sh refresh            on release/*: after a fix landed on
#                                          the branch, regenerate the changelog
#                                          and re-add the release commit
#   scripts/release.sh backmerge          after a release shipped: PR main ->
#                                          dev (merge commit, auto-merge)
#   scripts/release.sh notes [APP] [VERSION]
#                                         one version's changelog section
#   scripts/release.sh hotfix             on hotfix/* (from main): patch bump
#                                          + changelog + release commit
#   scripts/release.sh guard              CI: is this PR a sound release?
#   scripts/release.sh publish            CI: tag + GitHub Release on main
#                                          (the repo's, then each app whose
#                                          version moved; an app's also starts
#                                          its <app>-ios.yml on the new tag)
#   scripts/release.sh app-resolve APP TAG
#                                         CI (<app>-ios.yml): refuse a tag that
#                                          is not <app>-vX.Y.Z, whose crate
#                                          version differs, that has no
#                                          changelog section or is not on main;
#                                          print the marketing version
#   scripts/release.sh app-release APP TAG
#                                         CI: make sure the tag's GitHub Release
#                                          exists (idempotent)
#   scripts/release.sh app-record APP TAG MARKETING BUILD [RUN_URL]
#                                         CI: after the TestFlight upload, write
#                                          the marketing version + build number
#                                          into the release notes
#
# See docs/agents/release-workflow.md for the whole procedure.
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"
REPO="${GITHUB_REPOSITORY:-FastTrackStudios/studio}"
INTEGRATION_BRANCH="${INTEGRATION_BRANCH:-dev}"
PRODUCTION_BRANCH="${PRODUCTION_BRANCH:-main}"

die() { echo "release: $*" >&2; exit 1; }
note() { echo "release: $*" >&2; }

# git-cliff from PATH, else from nixpkgs (it is not in the dev shell, and
# adding it there would make every flake.lock bump an infra change).
cliff() {
    if command -v git-cliff >/dev/null 2>&1; then
        git-cliff "$@"
    elif command -v nix >/dev/null 2>&1; then
        nix run --accept-flake-config nixpkgs#git-cliff -- "$@"
    else
        die "git-cliff not found (and no nix to fetch it)"
    fi
}

# `[workspace.package] version` of Cargo.toml at a revision (default: the
# working tree).
version_at() {
    local src
    if [ -n "${1:-}" ]; then src="$(git show "$1:Cargo.toml")"; else src="$(cat Cargo.toml)"; fi
    printf '%s\n' "$src" \
        | sed -n '/^\[workspace\.package\]/,/^\[/{s/^version *= *"\([^"]*\)".*/\1/p;}' \
        | head -1
}

is_semver() { [[ "$1" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; }

# The release commit's subject for a version, as an ERE (a squash merge
# may append " (#N)"). With an app: `chore(release): <app>-v<version>`.
release_subject_re() { # <version> [app]
    local t; t="$(ctx_tag "${2:-}" "$1")"
    printf '^chore\\(release\\): %s( \\(#[0-9]+\\))?$' "${t//./\\.}"
}

# true when $1 > $2 (both X.Y.Z)
gt() { [ "$1" != "$2" ] && [ "$(printf '%s\n%s\n' "$1" "$2" | sort -V | tail -1)" = "$1" ]; }

bump() { # bump <X.Y.Z> <major|minor|patch>
    local IFS=.; read -r ma mi pa <<<"$1"
    case "$2" in
        major) echo "$((ma + 1)).0.0" ;;
        minor) echo "$ma.$((mi + 1)).0" ;;
        patch) echo "$ma.$mi.$((pa + 1))" ;;
        *) die "unknown bump '$2'" ;;
    esac
}

# The newest product tag reachable from HEAD. Per-app tags
# (`signal-v*`, `session-v*`, …) deliberately do not match.
last_tag() {
    git tag --list 'v[0-9]*' --merged "${1:-HEAD}" --sort=-v:refname \
        | grep -E '^v[0-9]+\.[0-9]+\.[0-9]+$' | head -1 || true
}

# ── per-app releases (Signal, Session) ──────────────────────────────────
# An app's version is the `[package] version` of its app crate; its tag is
# `<app>-v<version>`; its changelog is apps/<app>/CHANGELOG.md, generated
# from the commits that touched APP_PATHS since the app's last tag.
APPS="signal session"
APP_BASELINE="${APP_BASELINE:-0.1.0}"

app_check() {
    case "${1:-}" in signal|session) ;; *) die "unknown app '${1:-}' (signal or session)" ;; esac
}
app_manifest() { case "$1" in signal) echo apps/signal/desktop/Cargo.toml ;; session) echo apps/session/desktop/Cargo.toml ;; esac; }
app_changelog() { echo "apps/$1/CHANGELOG.md"; }
# What counts as a change to an app: its own tree and the shared crates and
# features it is built from (what the old iOS path filter watched), without
# the other app's tree. Overridable for a repo that moves things.
app_paths() { case "$1" in signal|session) echo "${APP_PATHS:-apps/$1 crates features}" ;; esac; }
app_exclude() { case "$1" in signal) echo "${APP_EXCLUDE:-apps/session features/session}" ;; session) echo "${APP_EXCLUDE:-apps/signal features/signal}" ;; esac; }
# The same as git pathspecs, for `git rev-list -- …`.
app_pathspec() { local p; for p in $(app_paths "$1"); do echo "$p"; done; for p in $(app_exclude "$1"); do echo ":(exclude)$p"; done; }
app_title() { case "$1" in signal) echo Signal ;; session) echo Session ;; esac; }
app_bundle_id() { echo "app.fasttrackstudio.$1"; }

# The app crate's `[package] version` at a revision (default: working tree).
# A `version.workspace = true` crate has none and reads as empty.
app_version_at() { # <app> [rev]
    local f src; f="$(app_manifest "$1")"
    if [ -n "${2:-}" ]; then src="$(git show "$2:$f" 2>/dev/null || true)"; else src="$(cat "$f")"; fi
    printf '%s\n' "$src" \
        | sed -n '/^\[package\]/,/^\[/{s/^version *= *"\([^"]*\)".*/\1/p;}' \
        | head -1
}

# The newest `<app>-vX.Y.Z` tag reachable from a revision.
app_last_tag() { # <app> [rev]
    git tag --list "$1-v[0-9]*" --merged "${2:-HEAD}" --sort=-v:refname \
        | grep -E "^$1-v[0-9]+\.[0-9]+\.[0-9]+$" | head -1 || true
}

# release/<tag> -> REL_APP: "" for the repo's own release/vX.Y.Z, the app for
# release/<app>-vX.Y.Z. Fails for anything else.
release_ref() { # <ref>
    REL_APP=""
    local r="${1#release/}"
    [ "$r" != "$1" ] || return 1
    case "$r" in
        v[0-9]*) ;;
        signal-v[0-9]*|session-v[0-9]*) REL_APP="${r%%-v*}" ;;
        *) return 1 ;;
    esac
}

# The release commit's tag, version, last tag and changelog for the repo
# (app = "") or an app. One set of helpers so refresh, pr and guard serve both.
ctx_tag() { if [ -n "$1" ]; then echo "$1-v$2"; else echo "v$2"; fi; } # <app> <ver>
ctx_version_at() { if [ -n "$1" ]; then app_version_at "$1" "${2:-}"; else version_at "${2:-}"; fi; }
ctx_last_tag() { if [ -n "$1" ]; then app_last_tag "$1" "${2:-HEAD}"; else last_tag "${2:-HEAD}"; fi; }
ctx_changelog() { if [ -n "$1" ]; then app_changelog "$1"; else echo CHANGELOG.md; fi; }

# git-cliff over an app's range: only the commits that touched the app's
# paths, labelled as version <v>. `--tag-pattern` matches nothing, so the
# repo's own `v*` tags inside the range do not split it into sections.
app_cliff() { # <app> <version> <from> <cliff args…>
    local app="$1" v="$2" from="$3" inc=() p; shift 3
    for p in $(app_paths "$app"); do inc+=(--include-path "$p/**"); done
    for p in $(app_exclude "$app"); do inc+=(--exclude-path "$p/**"); done
    cliff --tag "v$v" --tag-pattern '^__no_such_tag__$' "${inc[@]}" "$@" ${from:+"$from..HEAD"}
}

# The first release of an app has no range to list: it is the baseline.
app_baseline_section() { # <app> <version>
    printf '## [%s] - %s\n\n### Changes\n\n- First tagged release of %s: the baseline for per-app versions. The history before it is the git log.\n' \
        "$2" "$(date -u +%F)" "$(app_title "$1")"
}

# Git dependencies whose locked commit moved in a range — behaviour can
# arrive without a line of this repo's source changing (architect,
# keyflow, the vendor repo, …). Release notes carry the list.
git_deps_moved() { # <from> <to>
    [ -n "$1" ] || return 0
    git diff -U0 "$1" "$2" -- Cargo.lock \
        | grep -E '^\+source = "git\+' \
        | sed -E 's/^\+source = "git\+([^?#"]+).*/\1/' | sort -u || true
}

cmd_version() { version_at; }

cmd_notes() { # [APP] [VERSION]
    local app=""
    case "${1:-}" in signal|session) app="$1"; shift ;; esac
    local v="${1:-$(ctx_version_at "$app")}" f; f="$(ctx_changelog "$app")"
    [ -f "$f" ] || { note "no $f"; return 1; }
    awk -v want="## [$v]" '
        index($0, want) == 1 { on = 1; next }
        on && /^## \[/ { exit }
        on { print }
    ' "$f" | sed -e '/./,$!d' # drop leading blank lines
}

cmd_plan_app() { # <app>
    local app="$1" cur tag next
    app_check "$app"
    cur="$(app_version_at "$app")"; tag="$(app_last_tag "$app")"
    if [ -z "$tag" ]; then
        next="$APP_BASELINE"
    else
        next="$(bump "${tag#"$app"-v}" patch)"
    fi
    echo "$app crate version:    ${cur:-?} ($(app_manifest "$app"))"
    echo "last $app tag:         ${tag:-none}"
    echo "next $app release:     $next ($app-v$next; patch, the default; minor/major only when the Captain or Commander calls one)"
    echo "TestFlight:            uploads only from that tag, marketing version $next"
    if [ -n "$tag" ]; then
        local ps=() l
        while IFS= read -r l; do ps+=("$l"); done < <(app_pathspec "$app")
        echo "commits since tag:     $(git rev-list --count "$tag..HEAD" -- "${ps[@]}")"
        echo
        echo "── unreleased $app changelog ($tag..HEAD) ──"
        app_cliff "$app" "$next" "$tag" --strip header || true
    else
        echo
        echo "── $app's first release is the baseline: its section lists no commits ──"
    fi
}

cmd_plan() {
    case "${1:-}" in signal|session) cmd_plan_app "$1"; return ;; esac
    local cur tag next
    cur="$(version_at)"; tag="$(last_tag)"
    local cliff_next
    next="$(bump "$cur" patch)"
    cliff_next="$(cliff --bumped-version 2>/dev/null | sed 's/^v//' || true)"
    echo "version (Cargo.toml):  $cur"
    echo "last release tag:      ${tag:-none}"
    echo "commits since tag:     $(git rev-list --count ${tag:+$tag..}HEAD)"
    echo "next release:          $next (patch, the default; minor/major only when the Captain or Commander calls one)"
    echo "git-cliff would bump:  ${cliff_next:-?} (informational; opt in with: just release-prepare auto)"
    echo
    echo "── unreleased changelog (commits in ${tag:+$tag..}HEAD) ──"
    cliff --strip header ${next:+--tag "v$next"} ${tag:+"$tag..HEAD"} || true
    if [ -n "$tag" ]; then
        local d; d="$(git_deps_moved "$tag" HEAD)"
        echo "── git dependencies moved since $tag ──"
        echo "${d:-none}"
    fi
}

# prepare <app> [BUMP]: cut release/<app>-v<next> from origin/dev. The app's
# version is its crate's; the first release of an app is the baseline (0.1.0).
cmd_prepare_app() {
    local app="$1" want="${2:-patch}" cur last next branch
    app_check "$app"
    [ -z "$(git status --porcelain --untracked-files=no)" ] || die "working tree is dirty"
    git fetch --quiet --tags origin "$INTEGRATION_BRANCH" "$PRODUCTION_BRANCH"
    git merge-base --is-ancestor "origin/$PRODUCTION_BRANCH" "origin/$INTEGRATION_BRANCH" \
        || die "origin/$PRODUCTION_BRANCH is not in origin/$INTEGRATION_BRANCH: the last release has not been back-merged. Run: just release-backmerge (and let it merge) first."
    cur="$(app_version_at "$app" "origin/$INTEGRATION_BRANCH")"
    last="$(app_last_tag "$app" "origin/$INTEGRATION_BRANCH")"
    if [ -z "$last" ]; then
        case "$want" in
            patch) next="$APP_BASELINE" ;;
            minor|major|auto) die "$app has no $app-v* tag yet: its first release is $APP_BASELINE (patch), or an exact X.Y.Z" ;;
            *) is_semver "$want" || die "BUMP must be patch or X.Y.Z"
               next="$want" ;;
        esac
    else
        is_semver "$cur" || die "$(app_manifest "$app") version '$cur' is not X.Y.Z"
        [ "$cur" = "${last#"$app"-v}" ] \
            || die "origin/$INTEGRATION_BRANCH carries $app $cur but its last tag is $last: a release moves the version only through release-prepare"
        case "$want" in
            major|minor|patch) next="$(bump "$cur" "$want")" ;;
            auto) die "$app has no auto bump: patch (the default), minor, major or X.Y.Z" ;;
            *) is_semver "$want" || die "BUMP must be patch, minor, major or X.Y.Z"
               next="$want" ;;
        esac
        gt "$next" "$cur" || die "next version $next is not greater than $cur"
    fi
    git rev-parse -q --verify "refs/tags/$app-v$next" >/dev/null && die "tag $app-v$next already exists"
    if git ls-remote --exit-code --heads origin "release/$app-v$next" >/dev/null 2>&1; then
        die "release/$app-v$next is already open on origin. Finish (or close) that release first; a fix for it goes onto that branch (just release-refresh)."
    fi

    branch="release/$app-v$next"
    git switch --quiet -C "$branch" "origin/$INTEGRATION_BRANCH"
    note "cutting $branch ($app ${cur:-?} -> $next) from origin/$INTEGRATION_BRANCH $(git rev-parse --short "origin/$INTEGRATION_BRANCH")"
    # A refusal (nothing to release, no git-cliff) must not leave a bumped,
    # uncommitted tree on a half-made branch.
    if ! ( release_commit "$cur" "$next" "$app" ); then
        git reset --quiet --hard HEAD
        git clean --quiet -fd -- "$(dirname "$(app_changelog "$app")")" 2>/dev/null || true
        git switch --quiet --detach "origin/$INTEGRATION_BRANCH"
        git branch --quiet -D "$branch"
        die "no release was cut for $app (see above); $branch is gone and the tree is clean"
    fi
    cat >&2 <<EOF

Next:
  1. Read $(app_changelog "$app")'s [$next] section. Wrong line? Reword the commit
     on dev and re-run prepare — never hand-edit the generated file.
  2. just release-pr   — pushes $branch and opens it -> $PRODUCTION_BRANCH; the full checks run there.
  Merging it (merge commit) tags $app-v$next, publishes the GitHub Release and
  uploads TestFlight marketing version $next. $INTEGRATION_BRANCH stays open the whole time.
EOF
}

cmd_prepare() {
    case "${1:-}" in signal|session) cmd_prepare_app "$@"; return ;; esac
    # Patch by default, whatever the commits say: minor and major bumps
    # are a decision (the Captain or Commander calls them), not something
    # a feat commit triggers. `auto` asks git-cliff instead.
    local want="${1:-patch}" cur next branch
    [ -z "$(git status --porcelain --untracked-files=no)" ] || die "working tree is dirty"
    git fetch --quiet --tags origin "$INTEGRATION_BRANCH" "$PRODUCTION_BRANCH"
    # The last release must have come back to dev first: otherwise the new
    # branch lacks main's release merge, its version and changelog would
    # collide with main's, and the guard would refuse the PR anyway.
    git merge-base --is-ancestor "origin/$PRODUCTION_BRANCH" "origin/$INTEGRATION_BRANCH" \
        || die "origin/$PRODUCTION_BRANCH is not in origin/$INTEGRATION_BRANCH: the last release has not been back-merged. Run: just release-backmerge (and let it merge) first."
    cur="$(version_at "origin/$INTEGRATION_BRANCH")"
    is_semver "$cur" || die "Cargo.toml version '$cur' is not X.Y.Z"

    branch="release/pending"
    git switch --quiet -C "$branch" "origin/$INTEGRATION_BRANCH"

    case "$want" in
        auto) next="$(cliff --bumped-version | sed 's/^v//')"
              # Nothing conventional enough to bump: default to a minor
              # while 0.x (pre-1.0, a release is a feature drop).
              { [ -z "$next" ] || ! gt "$next" "$cur"; } && next="$(bump "$cur" minor)" ;;
        major|minor|patch) next="$(bump "$cur" "$want")" ;;
        *) is_semver "$want" || die "BUMP must be auto, major, minor, patch or X.Y.Z"
           next="$want" ;;
    esac
    gt "$next" "$cur" || die "next version $next is not greater than $cur"
    git rev-parse -q --verify "refs/tags/v$next" >/dev/null && die "tag v$next already exists"
    if git ls-remote --exit-code --heads origin "release/v$next" >/dev/null 2>&1; then
        git switch --quiet "$INTEGRATION_BRANCH" 2>/dev/null || git switch --quiet --detach "origin/$INTEGRATION_BRANCH"
        git branch --quiet -D "$branch"
        die "release/v$next is already open on origin. Finish (or close) that release first; a fix for it goes onto that branch (just release-refresh)."
    fi

    git branch --quiet -M "$branch" "release/v$next"
    note "cutting release/v$next (was $cur) from origin/$INTEGRATION_BRANCH $(git rev-parse --short "origin/$INTEGRATION_BRANCH")"
    release_commit "$cur" "$next"
    cat >&2 <<EOF

Next:
  1. Read CHANGELOG.md's [$next] section. Wrong line? Reword the commit
     on dev and re-run prepare — never hand-edit the generated file.
  2. just release-pr   — pushes release/v$next and opens it -> $PRODUCTION_BRANCH; the full checks run there.
  $INTEGRATION_BRANCH stays open the whole time: cards keep merging. A fix
  for this release is a PR into release/v$next, then just release-refresh.
EOF
}

# On a release/v* branch after a fix landed on it: regenerate the
# changelog (the fix joins this version's section) and end the branch
# with a release commit again, which is what the guard looks for.
cmd_refresh() {
    local ref v app tag
    ref="$(git rev-parse --abbrev-ref HEAD)"
    release_ref "$ref" || die "run this on the release/v* (or release/<app>-v*) branch (on '$ref')"
    app="$REL_APP"
    [ -z "$(git status --porcelain --untracked-files=no)" ] || die "working tree is dirty"
    git fetch --quiet --tags origin "$ref" 2>/dev/null || true
    if git rev-parse -q --verify "origin/$ref" >/dev/null; then
        git merge-base --is-ancestor "origin/$ref" HEAD \
            || die "origin/$ref has commits this checkout lacks: git pull --ff-only first"
    fi
    v="$(ctx_version_at "$app")"; tag="$(ctx_tag "$app" "$v")"
    [ "$ref" = "release/$tag" ] || die "branch $ref carries version $v"
    if [[ "$(git log -1 --format=%s)" =~ $(release_subject_re "$v" "$app") ]]; then
        note "the head is already the release commit — nothing to refresh"; return 0
    fi
    changelog_write "$v" "$app"
    git add "$(ctx_changelog "$app")"
    git commit --quiet --allow-empty -m "chore(release): $tag"
    note "committed: $(git log -1 --format='%h %s'). Push it: git push origin $ref"
}

# Bump the version (Cargo.toml, or an app crate's), Cargo.lock, regenerate
# the changelog, commit `chore(release): <tag>` on the current branch.
release_commit() { # <cur> <next> [app]
    local cur="$1" next="$2" app="${3:-}" m
    if [ -n "$app" ]; then
        m="$(app_manifest "$app")"
        # The crate's own version line (its [package] section).
        sed -i.bak "/^\[package\]/,/^\[/s/^version *= *\"[^\"]*\"/version = \"$next\"/" "$m"
        rm -f "$m.bak"
        [ "$(app_version_at "$app")" = "$next" ] || die "failed to rewrite [package] version in $m"
    else
        m=Cargo.toml
        # The one version line.
        sed -i.bak "/^\[workspace\.package\]/,/^\[/s/^version *= *\"$cur\"/version = \"$next\"/" Cargo.toml
        rm -f Cargo.toml.bak
        [ "$(version_at)" = "$next" ] || die "failed to rewrite [workspace.package] version"
    fi

    # Workspace members' entries in the lockfile follow; nothing else may
    # move. --offline first: a version bump needs no index.
    cargo update --workspace --offline 2>/dev/null || cargo update --workspace

    changelog_write "$next" "$app"

    git add "$m" Cargo.lock "$(ctx_changelog "$app")"
    git commit --quiet -m "chore(release): $(ctx_tag "$app" "$next")"
    note "committed: $(git log -1 --format='%h %s')"
}

# Write <version>'s section into CHANGELOG.md (replacing it if present),
# above every older section, which stay as released. The section holds
# exactly the commits reachable from HEAD and not from the last release
# tag — a git RANGE. git-cliff's own whole-history walk files commits
# under tags by date, and with release branches that is wrong: a card
# merged into dev while v0.2.4 was out would be listed under 0.2.4,
# which never shipped it.
#
# An app's section (changelog_write <v> <app>) is the same range, narrowed to
# the commits that touched the app's paths, since the app's last tag; an
# app's first release has no tag to start from and gets the baseline line.
changelog_write() { # <version> [app]
    local v="$1" app="${2:-}" from sec file
    file="$(ctx_changelog "$app")"
    from="$(ctx_last_tag "$app" HEAD)"
    sec="$(mktemp)"
    if [ -z "$app" ]; then
        # The first release creates the file with cliff.toml's header.
        [ -f "$file" ] || cliff --strip footer --tag "v$v" ${from:+"$from..HEAD"} \
            | sed '/^## \[/,$d' > "$file"
        cliff --tag "v$v" --strip all ${from:+"$from..HEAD"} > "$sec"
    elif [ -z "$from" ]; then
        app_baseline_section "$app" "$v" > "$sec"
    else
        app_cliff "$app" "$v" "$from" --strip all > "$sec"
        # git-cliff prints the heading even when no commit is left after the
        # path filter: an app release needs at least one line.
        grep -q '^- ' "$sec" \
            || die "nothing to release for $app since $from: no commit touched its paths ($(app_paths "$app"), without $(app_exclude "$app"))"
    fi
    grep -q "^## \[$v\]" "$sec" \
        || die "git-cliff produced no [$v] section: nothing to release since ${from:-the first commit}?"
    # An app's changelog is created, with cliff.toml's header, only now that
    # there is a section to put in it. No commit touched the path yet, so
    # git-cliff prints the header and no section.
    if [ -n "$app" ] && [ ! -f "$file" ]; then
        mkdir -p "$(dirname "$file")"
        cliff --strip footer --unreleased --include-path "$file" | sed '/^## \[/,$d' > "$file.new"
        mv "$file.new" "$file"
    fi
    awk -v want="## [$v]" -v sec="$sec" '
        function emit(   n, i, l, buf) {
            n = 0; while ((getline l < sec) > 0) buf[++n] = l
            while (n > 0 && buf[n] == "") n--          # no trailing blanks
            for (i = 1; i <= n; i++) print buf[i]
            print ""; done = 1
        }
        index($0, want) == 1 { skip = 1; if (!done) emit(); next }
        skip && /^## \[/ { skip = 0 }
        skip { next }
        /^## \[/ && !done { emit() }
        { print }
        END { if (!done) emit() }
    ' "$file" > "$sec.new"
    mv "$sec.new" "$file"
    rm -f "$sec"
    grep -q "^## \[$v\]" "$file" || die "$file has no [$v] section"
}

# A hotfix when NO release branch is open: run ON a `hotfix/<name>`
# branch cut from origin/main that already carries the fix commit(s).
# Adds the patch-bump release commit the guard requires. (With a release
# branch open, the fix goes onto that branch instead: same version, one
# PR, `refresh`.) After it ships, back-merge main into dev.
cmd_hotfix() {
    local cur next ref
    ref="$(git rev-parse --abbrev-ref HEAD)"
    case "$ref" in hotfix/*) ;; *) die "run this on a hotfix/* branch cut from origin/$PRODUCTION_BRANCH (on '$ref')" ;; esac
    [ -z "$(git status --porcelain --untracked-files=no)" ] || die "working tree is dirty"
    git fetch --quiet --tags origin "$PRODUCTION_BRANCH"
    git merge-base --is-ancestor "origin/$PRODUCTION_BRANCH" HEAD \
        || die "$ref does not contain origin/$PRODUCTION_BRANCH; rebase it onto main first"
    cur="$(version_at "origin/$PRODUCTION_BRANCH")"
    next="$(bump "$cur" patch)"
    git rev-parse -q --verify "refs/tags/v$next" >/dev/null && die "tag v$next already exists"
    if git ls-remote --exit-code --heads origin "release/v$next" >/dev/null 2>&1; then
        die "release/v$next is open: put the fix on it instead (PR into release/v$next, then just release-refresh)"
    fi
    note "hotfix v$next (was $cur) on $ref"
    release_commit "$cur" "$next"
    cat >&2 <<EOF

Next:
  1. just release-pr — pushes $ref and opens it -> $PRODUCTION_BRANCH. checks + the release guard run.
  2. Merge it with "Create a merge commit". deploy + TestFlight run; v$next is tagged.
  3. just release-backmerge — $PRODUCTION_BRANCH -> $INTEGRATION_BRANCH, so dev gets the fix and the bump.
EOF
}

# Push the current release/v* (or hotfix/*) branch and open its PR into
# main, with the changelog and moved git deps as the body.
cmd_pr() {
    local ref v body kind existing app="" tag
    ref="$(git rev-parse --abbrev-ref HEAD)"
    if release_ref "$ref"; then kind=Release; app="$REL_APP"
    else
        case "$ref" in
            hotfix/*) kind=Hotfix ;;
            *) die "run this on the release/v*, release/<app>-v* (or hotfix/*) branch (on '$ref'); just release-prepare makes one" ;;
        esac
    fi
    [ -z "$(git status --porcelain --untracked-files=no)" ] || die "working tree is dirty"
    v="$(ctx_version_at "$app")"; tag="$(ctx_tag "$app" "$v")"
    [[ "$(git log -1 --format=%s)" =~ $(release_subject_re "$v" "$app") ]] \
        || die "the head is not the release commit for $tag (just release-prepare / release-hotfix / release-refresh)"
    git fetch --quiet --tags origin "$PRODUCTION_BRANCH"
    git push --quiet origin "HEAD:refs/heads/$ref"
    existing="$(gh pr list --repo "$REPO" --head "$ref" --base "$PRODUCTION_BRANCH" --state open --json url --jq '.[0].url' 2>/dev/null || true)"
    if [ -n "$existing" ]; then
        note "pushed; the PR is already open: $existing"; return 0
    fi
    local from; from="$(ctx_last_tag "$app" "origin/$PRODUCTION_BRANCH")"
    body="$(mktemp)"
    {
        echo "$kind **$tag**: \`$ref\` → \`$PRODUCTION_BRANCH\` (source \`$(git rev-parse --short HEAD)\`)."
        echo
        echo "Merge with **Create a merge commit** (never squash or rebase): the merge"
        echo "commit's tree is the tree the checks below tested, and the \`$tag\` tag"
        echo "lands on this branch's tip, which must stay in main's history."
        echo "\`$INTEGRATION_BRANCH\` stays open meanwhile; after the release, \`just release-backmerge\`."
        echo
        if [ -n "$app" ]; then
            echo "On merge: release.yml tags \`$tag\`, publishes the GitHub Release ($(app_title "$app") $v,"
            echo "this app's changelog as the notes) and starts \`$app-ios\` on the tag: the"
            echo "TestFlight upload, marketing version **$v**, with the build number written back"
            echo "into the release notes. The sites and the other app are not released by this."
        else
            echo "On merge: deploy (session-web + signal-web); release.yml tags \`v$v\`,"
            echo "publishes the GitHub Release and starts the REAPER suites on the tag."
            echo "The iOS apps are NOT uploaded by this: they ship only from their own per-app"
            echo "tags (\`just release-prepare signal|session\` -> \`<app>-vX.Y.Z\`)."
        fi
        echo
        local d; d="$(git_deps_moved "$from" HEAD)"
        if [ -n "$d" ]; then
            echo "### Git dependencies moved"
            # shellcheck disable=SC2086 # $d is a word list
            printf -- '- %s\n' $d
            echo
        fi
        echo "### Changelog"
        cmd_notes ${app:+"$app"} "$v"
    } > "$body"
    gh pr create --repo "$REPO" --base "$PRODUCTION_BRANCH" --head "$ref" \
        --title "$kind $tag" --body-file "$body"
    rm -f "$body"
}

# After a release (or hotfix) reached main: bring main back into dev with
# a merge commit, so dev carries the bump, the changelog and any fix made
# on the release branch, and the next release branch contains main.
# Idempotent: nothing to do when main is already in dev.
# What the tip of main released: the tag named by its release branch's
# `chore(release): <tag>` commit (the merge's second parent), else v<version>.
# A back-merge branch is named after it, so an app release and the repo's
# never share one.
backmerge_label() {
    local s
    s="$(git log -1 --format=%s "origin/$PRODUCTION_BRANCH^2" 2>/dev/null || true)"
    if [[ "$s" =~ ^chore\(release\):\ ((signal-|session-)?v[0-9]+\.[0-9]+\.[0-9]+)( |$) ]]; then
        echo "${BASH_REMATCH[1]}"
    else
        echo "v$(version_at "origin/$PRODUCTION_BRANCH")"
    fi
}

cmd_backmerge() {
    local v sha branch existing
    git fetch --quiet --tags origin "$INTEGRATION_BRANCH" "$PRODUCTION_BRANCH"
    if git merge-base --is-ancestor "origin/$PRODUCTION_BRANCH" "origin/$INTEGRATION_BRANCH"; then
        note "origin/$PRODUCTION_BRANCH is already in origin/$INTEGRATION_BRANCH — nothing to back-merge"; return 0
    fi
    sha="$(git rev-parse "origin/$PRODUCTION_BRANCH")"
    v="$(backmerge_label)"
    branch="backmerge/$v"
    existing="$(gh pr list --repo "$REPO" --head "$branch" --base "$INTEGRATION_BRANCH" --state open --json url --jq '.[0].url' 2>/dev/null || true)"
    if [ -z "$existing" ]; then
        # A branch, not main itself, as the PR head: a conflict (a card that
        # touched a workspace member's Cargo.lock entry next to its version
        # line) is resolved by merging dev into this branch, never on main.
        git push --quiet origin "$sha:refs/heads/$branch"
        existing="$(gh pr create --repo "$REPO" --base "$INTEGRATION_BRANCH" --head "$branch" \
            --title "chore(release): back-merge $v into $INTEGRATION_BRANCH" \
            --body "Brings \`$PRODUCTION_BRANCH\` ($(git rev-parse --short "$sha"), $v) back into \`$INTEGRATION_BRANCH\`: the version bump, the changelog and any fix made on the release branch. **Merge commit**, never squash: dev must contain main for the next release. Opened by \`just release-backmerge\`." | tail -1)"
    fi
    local subj="Merge $PRODUCTION_BRANCH into $INTEGRATION_BRANCH after $v"
    gh pr merge "$existing" --repo "$REPO" --merge --auto --subject "$subj" \
        || gh pr merge "$existing" --repo "$REPO" --merge --subject "$subj" \
        || note "could not enable auto-merge; merge $existing with a merge commit once its title check is green"
    note "back-merge: $existing"
    if ! git merge-tree --write-tree "origin/$INTEGRATION_BRANCH" "$sha" >/dev/null 2>&1; then
        note "it CONFLICTS: git switch $branch && git merge origin/$INTEGRATION_BRANCH, resolve (Cargo.lock: cargo update --workspace), push $branch"
    fi
}

# CI, on a pull request into main. Fails unless merging this PR would
# ship exactly the tree the checks tested, at a new version, with notes.
cmd_guard() {
    local base="${BASE_SHA:?}" head="${HEAD_SHA:?}" ref="${HEAD_REF:?}"
    local v vb merged subject cut="" ok=1 app="" tag cl other
    fail() { echo "::error::$*"; ok=0; }

    # Bootstrap: until `dev` exists main still takes
    # ordinary PRs, including the one that adds this guard.
    if ! git ls-remote --exit-code --heads origin "$INTEGRATION_BRANCH" >/dev/null 2>&1; then
        echo "::notice::no '$INTEGRATION_BRANCH' branch yet — release guard not enforced"
        return 0
    fi
    git fetch --quiet --tags origin \
        "+refs/heads/$INTEGRATION_BRANCH:refs/remotes/origin/$INTEGRATION_BRANCH" 2>/dev/null || true

    case "$ref" in
        release/signal-v*|release/session-v*) release_ref "$ref" && app="$REL_APP" ;;
    esac

    if [ -n "$app" ]; then
        # A per-app release (Signal, Session): the app crate's version, the
        # tag <app>-v<version>, apps/<app>/CHANGELOG.md. It moves that
        # version and nothing else, so one release is one tag.
        v="$(app_version_at "$app" "$head")"; vb="$(app_version_at "$app" "$base")"
        tag="$app-v$v"; cl="$(app_changelog "$app")"
        [ "$ref" = "release/$tag" ] \
            || fail "branch '$ref' carries $app version '$v'; an app release branch is named release/$app-v<its version> (just release-prepare $app)"
        [ "$(version_at "$head")" = "$(version_at "$base")" ] \
            || fail "an app release must not move the repo's version ([workspace.package]): that is the repo release's (just release-prepare)"
        for other in $APPS; do
            [ "$other" = "$app" ] && continue
            [ "$(app_version_at "$other" "$head")" = "$(app_version_at "$other" "$base")" ] \
                || fail "an app release moves one app: $other's version changed too"
        done
        if ! is_semver "$v"; then fail "$(app_manifest "$app") version '$v' is not X.Y.Z"
        elif is_semver "$vb" && ! gt "$v" "$vb"; then fail "version $v is not greater than main's $vb — cut the release with just release-prepare $app"
        fi
    else
        v="$(version_at "$head")"; vb="$(version_at "$base")"
        tag="v$v"; cl=CHANGELOG.md
        case "$ref" in
            release/v*) [ "$ref" = "release/v$v" ] \
                            || fail "branch '$ref' carries version '$v'; a release branch is named release/v<its version> (just release-prepare)" ;;
            hotfix/*) ;;
            *) fail "release PRs come from release/vX.Y.Z or release/<app>-vX.Y.Z (just release-prepare) or hotfix/*, not '$ref'. Other PRs target '$INTEGRATION_BRANCH'." ;;
        esac

        if ! is_semver "$v"; then fail "Cargo.toml version '$v' is not X.Y.Z"
        elif ! gt "$v" "$vb"; then fail "version $v is not greater than main's $vb — cut the release with just release-prepare"
        fi
    fi
    git rev-parse -q --verify "refs/tags/$tag" >/dev/null && fail "tag $tag already exists"

    git show "$head:$cl" 2>/dev/null | grep -q "^## \[$v\]" \
        || fail "$cl at the head has no [$v] section"

    subject="$(git log -1 --format=%s "$head")"
    [[ "$subject" =~ $(release_subject_re "$v" "$app") ]] \
        || fail "the head commit must be the release commit 'chore(release): $tag' (it is '$subject'). A fix landed on $ref after it: run just release-refresh on the branch and push."

    # Where the release was cut: the parent of its first release commit.
    # It must be a commit of dev — a release ships what dev integrated,
    # plus at most fixes made on the release branch itself. (Not dev's
    # HEAD: dev keeps moving while the release is out.)
    if [[ "$ref" == release/* ]]; then
        local first
        first="$(git log --reverse --format='%H %s' "$base..$head" \
            | while read -r h s; do [[ "$s" =~ $(release_subject_re "$v" "$app") ]] && { echo "$h"; break; }; done || true)"
        if [ -z "$first" ]; then
            fail "no 'chore(release): $tag' commit between main and the head"
        elif ! git rev-parse -q --verify "origin/$INTEGRATION_BRANCH" >/dev/null; then
            fail "cannot see origin/$INTEGRATION_BRANCH to check where $ref was cut"
        else
            cut="$(git rev-parse "$first^")"
            git merge-base --is-ancestor "$cut" "origin/$INTEGRATION_BRANCH" \
                || fail "$ref was not cut from $INTEGRATION_BRANCH (its base $(git rev-parse --short "$cut") is not in origin/$INTEGRATION_BRANCH). Re-cut it: just release-prepare${app:+ $app}"
        fi
    fi

    # Main must already be in the head: the back-merge of the last release
    # happened before this branch was cut (or, for a hotfix, it was cut
    # from main).
    git merge-base --is-ancestor "$base" "$head" \
        || fail "main ($(git rev-parse --short "$base")) is not in $ref: back-merge main into $INTEGRATION_BRANCH (just release-backmerge) and re-cut, or merge origin/main into $ref and run just release-refresh"

    # Tree identity: the merge commit main will get must have the head's
    # tree — so checks (which test this tree), deploy (which builds the
    # merge commit) and the tag (on the head) all name the same source.
    merged="$(git merge-tree --write-tree "$base" "$head" 2>/dev/null | head -1 || true)"
    [ "$merged" = "$(git rev-parse "$head^{tree}")" ] \
        || fail "merging into main would not reproduce the head's tree"

    {
        echo "### Release guard: $tag ($ref → main)"
        echo "- version: $vb → $v"
        echo "- head: \`$(git rev-parse --short "$head")\` $subject"
        [ -n "$cut" ] && echo "- cut from $INTEGRATION_BRANCH at: \`$(git rev-parse --short "$cut")\` ($(git rev-list --count "$cut..origin/$INTEGRATION_BRANCH") commits on $INTEGRATION_BRANCH since — they ship next time)"
        [ -n "$cut" ] && echo "- fixes on the release branch: $(git log --format=%s "$cut..$head" | grep -cvE "$(release_subject_re "$v" "$app")" || true)"
        echo "- merge tree identical to head tree: $([ "$merged" = "$(git rev-parse "$head^{tree}")" ] && echo yes || echo NO)"
        [ -n "$app" ] && echo "- on merge: $tag, its GitHub Release and the $app-ios TestFlight upload (marketing version $v)"
        local d; d="$(git_deps_moved "$(ctx_last_tag "$app" "$base")" "$head" | paste -sd, -)"
        echo "- git deps moved since last release: ${d:-none}"
    } >> "${GITHUB_STEP_SUMMARY:-/dev/stderr}"
    [ "$ok" = 1 ] || exit 1
    echo "release guard: ok ($tag)"
}

# CI, on a push to main (or by hand). Idempotent. studio's product is
# the apps, not the two sites, so the tag does not wait for deploy.
publish_repo() {
    local v tag target prev notes
    v="$(version_at HEAD)"; tag="v$v"
    is_semver "$v" || die "Cargo.toml version '$v' is not X.Y.Z"
    if gh release view "$tag" --repo "$REPO" >/dev/null 2>&1; then
        note "release $tag already exists — nothing to do"; return 0
    fi
    # Only a release commit carries its own CHANGELOG section. A push to
    # main without one (the bootstrap PR, a docs-only merge) is not a
    # release, and must not publish a Release for an old tag.
    if ! grep -q "^## \[$v\]" CHANGELOG.md 2>/dev/null; then
        note "CHANGELOG.md has no [$v] section — not a release commit, nothing to publish"; return 0
    fi
    # Tag the release branch's tip (the merge's second parent) when it
    # carries the same tree: that commit reaches dev with the back-merge,
    # so the next changelog starts after it. A plain commit is tagged itself.
    target="$(git rev-parse HEAD)"
    if git rev-parse -q --verify HEAD^2 >/dev/null \
        && [ "$(git rev-parse 'HEAD^2^{tree}')" = "$(git rev-parse 'HEAD^{tree}')" ]; then
        target="$(git rev-parse HEAD^2)"
    fi
    if git rev-parse -q --verify "refs/tags/$tag" >/dev/null; then
        target="$(git rev-parse "$tag^{commit}")"
        note "tag $tag exists without a release; publishing it"
    fi
    prev="$(last_tag "$target^")"

    notes="$(mktemp)"
    {
        cmd_notes "$v" || true
        local d; d="$(git_deps_moved "$prev" "$target")"
        if [ -n "$d" ]; then
            echo
            echo "### Git dependencies moved"
            # shellcheck disable=SC2086 # $d is a word list
            printf -- '- %s\n' $d
        fi
        echo
        echo "---"
        echo "Source \`$(git rev-parse --short "$target")\`, released from main \`$(git rev-parse --short HEAD)\` (site images \`sha-$(git rev-parse --short HEAD)\`)."
        [ -n "$prev" ] && echo "Full diff: https://github.com/$REPO/compare/$prev...$tag"
    } > "$notes"
    [ -s "$notes" ] || die "no release notes for $v"

    gh release create "$tag" --repo "$REPO" --target "$target" \
        --title "studio $v" --notes-file "$notes" --latest
    rm -f "$notes"
    note "published https://github.com/$REPO/releases/tag/$tag"

    # A tag created with the workflow's GITHUB_TOKEN starts no workflows,
    # so reaper.yml's `push: tags` never sees it. A workflow_dispatch is
    # the one event that token may start: run the REAPER suites on the tag.
    if [ "${RELEASE_DISPATCH_REAPER:-1}" = 1 ]; then
        if gh workflow run reaper.yml --repo "$REPO" --ref "$tag"; then
            note "dispatched reaper-integration on $tag"
        else
            note "could not dispatch reaper-integration on $tag (run it by hand)"
        fi
    fi
}

# The block the TestFlight upload fills in, kept at the end of an app's
# release notes between these markers.
TF_BEGIN='<!-- testflight:begin -->'
TF_END='<!-- testflight:end -->'

# An app's GitHub Release, once its release reached main (or by hand, for a
# tag that exists). Idempotent. With no tag argument, HEAD's crate version
# names it, and only a release commit (one with a changelog section) does.
# A tag this creates is made by GITHUB_TOKEN and starts no workflow, so the
# app's TestFlight workflow is dispatched on it; a tag that already existed
# was pushed by someone whose push already started it.
app_publish() { # <app> [tag]
    local app="$1" tag="${2:-}" v target prev notes existed=0 d
    app_check "$app"
    if [ -n "$tag" ]; then v="${tag#"$app"-v}"; else v="$(app_version_at "$app" HEAD)"; tag="$app-v$v"; fi
    is_semver "$v" || { note "$app version '$v' is not X.Y.Z — not released, nothing to publish"; return 0; }
    if gh release view "$tag" --repo "$REPO" >/dev/null 2>&1; then
        note "release $tag already exists — nothing to do"; return 0
    fi
    # Only a release commit carries its own section of the app's changelog.
    if ! grep -q "^## \[$v\]" "$(app_changelog "$app")" 2>/dev/null; then
        note "$(app_changelog "$app") has no [$v] section — not a release commit, nothing to publish for $app"; return 0
    fi
    target="$(git rev-parse HEAD)"
    if git rev-parse -q --verify HEAD^2 >/dev/null \
        && [ "$(git rev-parse 'HEAD^2^{tree}')" = "$(git rev-parse 'HEAD^{tree}')" ]; then
        target="$(git rev-parse HEAD^2)"
    fi
    if git rev-parse -q --verify "refs/tags/$tag" >/dev/null; then
        existed=1; target="$(git rev-parse "$tag^{commit}")"
        note "tag $tag exists without a release; publishing it"
    fi
    prev="$(app_last_tag "$app" "$target^")"

    notes="$(mktemp)"
    {
        cmd_notes "$app" "$v" || true
        d="$(git_deps_moved "$prev" "$target")"
        if [ -n "$d" ]; then
            echo
            echo "### Git dependencies moved"
            # shellcheck disable=SC2086 # $d is a word list
            printf -- '- %s\n' $d
        fi
        echo
        echo "---"
        echo "Source \`$(git rev-parse --short "$target")\`, released from main \`$(git rev-parse --short HEAD)\`."
        [ -n "$prev" ] && echo "Full diff: https://github.com/$REPO/compare/$prev...$tag"
        echo
        echo "$TF_BEGIN"
        echo "### TestFlight"
        echo "Pending: \`$app-ios\` builds this tag and writes the marketing version (**$v**) and the build number here."
        echo "$TF_END"
    } > "$notes"
    [ -s "$notes" ] || die "no release notes for $app $v"

    gh release create "$tag" --repo "$REPO" --target "$target" \
        --title "$(app_title "$app") $v" --notes-file "$notes" --latest=false
    rm -f "$notes"
    note "published https://github.com/$REPO/releases/tag/$tag"

    if [ "$existed" = 0 ] && [ "${RELEASE_DISPATCH_IOS:-1}" = 1 ]; then
        if gh workflow run "$app-ios.yml" --repo "$REPO" --ref "$tag" -f tag="$tag"; then
            note "dispatched $app-ios on $tag (TestFlight marketing version $v)"
        else
            note "could not dispatch $app-ios on $tag (run it by hand: gh workflow run $app-ios.yml --ref $tag -f tag=$tag)"
        fi
    fi
}

cmd_publish() {
    local a
    publish_repo
    for a in $APPS; do app_publish "$a"; done
}

# CI, first job of <app>-ios.yml, run in a checkout of the tag. TestFlight
# ships exactly the tag: refuse a tag that is not <app>-vX.Y.Z, an app crate
# whose version is not the tag's, a tag without its changelog section, a
# commit that is not in main. Prints the marketing version.
cmd_app_resolve() { # <app> <tag>
    local app="${1:-}" tag="${2:-}" v cv re sha
    app_check "$app"
    re="^$app-v[0-9]+\\.[0-9]+\\.[0-9]+\$"
    [[ "$tag" =~ $re ]] || die "tag '$tag' does not match $re: TestFlight uploads only from a per-app release tag"
    v="${tag#"$app"-v}"
    cv="$(app_version_at "$app")"
    [ "$cv" = "$v" ] \
        || die "$(app_manifest "$app") says version '$cv' but the tag is $tag ($v): the marketing version is the tag's, so the crate must carry it (release the app with just release-prepare $app)"
    grep -q "^## \[$v\]" "$(app_changelog "$app")" 2>/dev/null \
        || die "$(app_changelog "$app") has no [$v] section: $tag is not a release commit"
    sha="$(git rev-parse HEAD)"
    if git rev-parse -q --verify "refs/tags/$tag" >/dev/null; then
        [ "$(git rev-parse "$tag^{commit}")" = "$sha" ] || die "this checkout ($sha) is not $tag"
    fi
    git fetch --quiet origin "$PRODUCTION_BRANCH"
    git merge-base --is-ancestor "$sha" "origin/$PRODUCTION_BRANCH" \
        || die "$tag ($(git rev-parse --short "$sha")) is not in origin/$PRODUCTION_BRANCH: only a release that reached $PRODUCTION_BRANCH goes to TestFlight"
    note "$tag: marketing version $v, commit $(git rev-parse --short "$sha"), bundle $(app_bundle_id "$app")"
    if [ -n "${GITHUB_OUTPUT:-}" ]; then
        { echo "version=$v"; echo "sha=$sha"; echo "tag=$tag"; } >> "$GITHUB_OUTPUT"
    fi
    echo "$v"
}

cmd_app_release() { # <app> <tag>
    app_check "${1:-}"
    [ -n "${2:-}" ] || die "usage: app-release <app> <tag>"
    app_publish "$1" "$2"
}

# CI, last job of <app>-ios.yml: write what was uploaded into the release
# notes, so the GitHub Release and the TestFlight build name each other.
# Builds accumulate (a re-run uploads a new build of the same version).
cmd_app_record() { # <app> <tag> <marketing> <build> [run-url]
    local app="${1:-}" tag="${2:-}" mv="${3:-}" build="${4:-}" run="${5:-}" body keep prior line out
    app_check "$app"
    [ "$tag" = "$app-v$mv" ] || die "marketing version '$mv' is not the version of tag '$tag'"
    [[ "$build" =~ ^[0-9]+$ ]] || die "build number '$build' is not a number"
    body="$(gh release view "$tag" --repo "$REPO" --json body --jq .body)" \
        || die "no GitHub Release for $tag (TestFlight needs one: app-release)"
    prior="$(printf '%s\n' "$body" | sed -n "\\#$TF_BEGIN#,\\#$TF_END#p" | grep -E '^- build ' || true)"
    keep="$(printf '%s\n' "$body" | sed "\\#$TF_BEGIN#,\\#$TF_END#d")"
    line="- build $build, $(date -u +%FT%TZ)${run:+, [run]($run)}"
    out="$(mktemp)"
    {
        printf '%s\n' "$keep" | sed -e :a -e '/^\n*$/{$d;N;ba' -e '}'
        echo
        echo "$TF_BEGIN"
        echo "### TestFlight"
        echo "Marketing version **$mv** (CFBundleShortVersionString) == this release, \`$tag\`. Bundle id \`$(app_bundle_id "$app")\`."
        { [ -n "$prior" ] && printf '%s\n' "$prior"; echo "$line"; } | awk '!seen[$0]++'
        echo "$TF_END"
    } > "$out"
    gh release edit "$tag" --repo "$REPO" --notes-file "$out"
    rm -f "$out"
    note "recorded on $tag: marketing $mv, build $build"
}


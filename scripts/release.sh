#!/usr/bin/env bash
# studio releases: ONE version, ONE changelog, ONE tag, ONE GitHub Release.
#
# The version lives in ONE place, `[workspace.package] version` in the
# root Cargo.toml. Every crate that says `version.workspace = true` follows
# it, and that includes both iOS app crates (apps/signal/desktop,
# apps/session/desktop), so Signal and Session can never differ: Signal
# and Session are the same build, and a change to one almost always
# touches the other. There are no per-app tags, branches or changelogs.
#
# A release is the `v<version>` git tag and its GitHub Release, cut when
# the release reaches main. That one tag drives BOTH TestFlight uploads
# (signal-ios.yml, session-ios.yml): the marketing version of each is the
# tag's version, and each writes its build number into the same Release's
# notes. Nothing else uploads to TestFlight. Versions start at 0.1.0 and
# only the patch moves (0.1.9 -> 0.1.10, never rolling over) unless the
# Captain or Commander calls a minor/major. The plugins' tags are not
# covered here.
#
# The changelog is GENERATED by git-cliff (cliff.toml) from the commit
# subjects on `dev`. PRs into dev are squash-merged with a
# conventional-commit title, so each PR is one changelog line; commits
# pushed to dev directly land under "Changes". Edit the commit, not the
# file.
#
# A release is a BRANCH, `release/v<next>`, cut from dev's head. Dev never
# freezes: cards keep landing while the release branch is checked,
# merged into main and tagged. Afterwards main is back-merged into dev,
# which is how dev gets the bump, the changelog and any fix made on the
# release branch.
#
#   scripts/release.sh version            the current version
#   scripts/release.sh plan               what the next release would be
#   scripts/release.sh prepare [BUMP]     cut release/v<next> from origin/dev:
#                                          bump + changelog + release commit
#                                          (BUMP: patch (default), minor,
#                                          major, auto or X.Y.Z; minor/major
#                                          only when the Captain or
#                                          Commander calls one)
#   scripts/release.sh pr                 push the release (or hotfix) branch
#                                          and open its PR into main
#   scripts/release.sh refresh            on release/v*: after a fix landed on
#                                          the branch, regenerate the changelog
#                                          and re-add the release commit
#   scripts/release.sh backmerge          after a release shipped: PR main ->
#                                          dev (merge commit, auto-merge)
#   scripts/release.sh notes [VERSION]    one version's changelog section
#   scripts/release.sh hotfix             on hotfix/* (from main): patch bump
#                                          + changelog + release commit
#   scripts/release.sh guard              CI: is this PR a sound release?
#   scripts/release.sh publish            CI: tag + GitHub Release on main, then
#                                          the REAPER suites and BOTH iOS
#                                          TestFlight workflows on the new tag
#   scripts/release.sh ios-resolve APP TAG
#                                         CI (<app>-ios.yml): refuse a tag that
#                                          is not vX.Y.Z, whose app crate
#                                          version differs, that has no
#                                          changelog section or is not on main;
#                                          print the marketing version
#   scripts/release.sh ios-release TAG    CI: make sure the tag's GitHub Release
#                                          exists (idempotent, safe to run from
#                                          both iOS workflows at once)
#   scripts/release.sh ios-record APP TAG MARKETING BUILD [RUN_URL]
#                                         CI: after the TestFlight upload, write
#                                          the marketing version + build number
#                                          into the release notes (one line per
#                                          app; safe to run concurrently)
#
# See docs/agents/release-workflow.md for the whole procedure.
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"
REPO="${GITHUB_REPOSITORY:-FastTrackStudios/studio}"
INTEGRATION_BRANCH="${INTEGRATION_BRANCH:-dev}"
PRODUCTION_BRANCH="${PRODUCTION_BRANCH:-main}"

die() { echo "release: $*" >&2; exit 1; }
note() { echo "release: $*" >&2; }

# git-cliff from PATH, else from nixpkgs (it is not in the dev shell, and
# adding it there would make every flake.lock bump an infra change).
cliff() {
    if command -v git-cliff >/dev/null 2>&1; then
        git-cliff "$@"
    elif command -v nix >/dev/null 2>&1; then
        nix run --accept-flake-config nixpkgs#git-cliff -- "$@"
    else
        die "git-cliff not found (and no nix to fetch it)"
    fi
}

# `[workspace.package] version` of Cargo.toml at a revision (default: the
# working tree).
version_at() {
    local src
    if [ -n "${1:-}" ]; then src="$(git show "$1:Cargo.toml")"; else src="$(cat Cargo.toml)"; fi
    printf '%s\n' "$src" \
        | sed -n '/^\[workspace\.package\]/,/^\[/{s/^version *= *"\([^"]*\)".*/\1/p;}' \
        | head -1
}

is_semver() { [[ "$1" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; }

# The release commit's subject for a version, as an ERE (a squash merge
# may append " (#N)").
release_subject_re() { # <version>
    printf '^chore\\(release\\): v%s( \\(#[0-9]+\\))?$' "${1//./\\.}"
}

# true when $1 > $2 (both X.Y.Z)
gt() { [ "$1" != "$2" ] && [ "$(printf '%s\n%s\n' "$1" "$2" | sort -V | tail -1)" = "$1" ]; }

bump() { # bump <X.Y.Z> <major|minor|patch>
    local IFS=.; read -r ma mi pa <<<"$1"
    case "$2" in
        major) echo "$((ma + 1)).0.0" ;;
        minor) echo "$ma.$((mi + 1)).0" ;;
        patch) echo "$ma.$mi.$((pa + 1))" ;;
        *) die "unknown bump '$2'" ;;
    esac
}

# The newest product tag reachable from HEAD.
last_tag() {
    git tag --list 'v[0-9]*' --merged "${1:-HEAD}" --sort=-v:refname \
        | grep -E '^v[0-9]+\.[0-9]+\.[0-9]+$' | head -1 || true
}

# ── the iOS apps (Signal, Session) ───────────────────────────────────────
# They are not released on their own: they are built from the one `v<version>`
# tag. Their crates follow the workspace version; the helpers below read
# that back so the guard and the TestFlight gate can prove it.
IOS_APPS="signal session"

ios_check() {
    case "${1:-}" in signal|session) ;; *) die "unknown iOS app '${1:-}' (signal or session)" ;; esac
}
ios_manifest() { case "$1" in signal) echo apps/signal/desktop/Cargo.toml ;; session) echo apps/session/desktop/Cargo.toml ;; esac; }
ios_title() { case "$1" in signal) echo Signal ;; session) echo Session ;; esac; }
ios_bundle_id() { echo "app.fasttrackstudio.$1"; }

# The version an app crate resolves to at a revision (default: working
# tree): the workspace version when it says `version.workspace = true`, else
# its own literal `[package] version`. Empty when neither is there.
crate_version_at() { # <app> [rev]
    local f src pkg; f="$(ios_manifest "$1")"
    if [ -n "${2:-}" ]; then src="$(git show "$2:$f" 2>/dev/null || true)"; else src="$(cat "$f" 2>/dev/null || true)"; fi
    pkg="$(printf '%s\n' "$src" | sed -n '/^\[package\]/,/^\[/p')"
    if grep -Eq '^version(\.workspace *= *true| *= *\{ *workspace *= *true *\})' <<<"$pkg"; then
        version_at "${2:-}"
    else
        printf '%s\n' "$pkg" | sed -n 's/^version *= *"\([^"]*\)".*/\1/p' | head -1
    fi
}

# Git dependencies whose locked commit moved in a range — behaviour can
# arrive without a line of this repo's source changing (architect,
# keyflow, the vendor repo, …). Release notes carry the list.
git_deps_moved() { # <from> <to>
    [ -n "$1" ] || return 0
    git diff -U0 "$1" "$2" -- Cargo.lock \
        | grep -E '^\+source = "git\+' \
        | sed -E 's/^\+source = "git\+([^?#"]+).*/\1/' | sort -u || true
}

cmd_version() { version_at; }

cmd_notes() { # [VERSION]
    local v="${1:-$(version_at)}" f=CHANGELOG.md
    [ -f "$f" ] || { note "no $f"; return 1; }
    awk -v want="## [$v]" '
        index($0, want) == 1 { on = 1; next }
        on && /^## \[/ { exit }
        on { print }
    ' "$f" | sed -e '/./,$!d' # drop leading blank lines
}

cmd_plan() {
    local cur tag next a cv
    cur="$(version_at)"; tag="$(last_tag)"
    local cliff_next
    next="$(bump "$cur" patch)"
    cliff_next="$(cliff --bumped-version 2>/dev/null | sed 's/^v//' || true)"
    echo "version (Cargo.toml):  $cur"
    for a in $IOS_APPS; do
        cv="$(crate_version_at "$a")"
        echo "$a crate version:    ${cv:-?}$([ "$cv" = "$cur" ] || echo '   <-- differs from the workspace version')"
    done
    echo "last release tag:      ${tag:-none}"
    echo "commits since tag:     $(git rev-list --count ${tag:+$tag..}HEAD)"
    echo "next release:          $next (patch, the default; minor/major only when the Captain or Commander calls one)"
    echo "                       one tag v$next and one GitHub Release for Signal + Session; both TestFlight uploads come from it"
    echo "git-cliff would bump:  ${cliff_next:-?} (informational; opt in with: just release-prepare auto)"
    echo
    echo "── unreleased changelog (commits in ${tag:+$tag..}HEAD) ──"
    cliff --strip header ${next:+--tag "v$next"} ${tag:+"$tag..HEAD"} || true
    if [ -n "$tag" ]; then
        local d; d="$(git_deps_moved "$tag" HEAD)"
        echo "── git dependencies moved since $tag ──"
        echo "${d:-none}"
    fi
}

cmd_prepare() {
    # Patch by default, whatever the commits say: minor and major bumps
    # are a decision (the Captain or Commander calls them), not something
    # a feat commit triggers. `auto` asks git-cliff instead.
    local want="${1:-patch}" cur next branch
    [ -z "$(git status --porcelain --untracked-files=no)" ] || die "working tree is dirty"
    git fetch --quiet --tags origin "$INTEGRATION_BRANCH" "$PRODUCTION_BRANCH"
    # The last release must have come back to dev first: otherwise the new
    # branch lacks main's release merge, its version and changelog would
    # collide with main's, and the guard would refuse the PR anyway.
    git merge-base --is-ancestor "origin/$PRODUCTION_BRANCH" "origin/$INTEGRATION_BRANCH" \
        || die "origin/$PRODUCTION_BRANCH is not in origin/$INTEGRATION_BRANCH: the last release has not been back-merged. Run: just release-backmerge (and let it merge) first."
    cur="$(version_at "origin/$INTEGRATION_BRANCH")"
    is_semver "$cur" || die "Cargo.toml version '$cur' is not X.Y.Z"

    branch="release/pending"
    git switch --quiet -C "$branch" "origin/$INTEGRATION_BRANCH"

    case "$want" in
        auto) next="$(cliff --bumped-version | sed 's/^v//')"
              # Nothing conventional enough to bump: default to a minor
              # while 0.x (pre-1.0, a release is a feature drop).
              { [ -z "$next" ] || ! gt "$next" "$cur"; } && next="$(bump "$cur" minor)" ;;
        major|minor|patch) next="$(bump "$cur" "$want")" ;;
        *) is_semver "$want" || die "BUMP must be auto, major, minor, patch or X.Y.Z"
           next="$want" ;;
    esac
    gt "$next" "$cur" || die "next version $next is not greater than $cur"
    git rev-parse -q --verify "refs/tags/v$next" >/dev/null && die "tag v$next already exists"
    if git ls-remote --exit-code --heads origin "release/v$next" >/dev/null 2>&1; then
        git switch --quiet "$INTEGRATION_BRANCH" 2>/dev/null || git switch --quiet --detach "origin/$INTEGRATION_BRANCH"
        git branch --quiet -D "$branch"
        die "release/v$next is already open on origin. Finish (or close) that release first; a fix for it goes onto that branch (just release-refresh)."
    fi

    git branch --quiet -M "$branch" "release/v$next"
    note "cutting release/v$next (was $cur) from origin/$INTEGRATION_BRANCH $(git rev-parse --short "origin/$INTEGRATION_BRANCH")"
    release_commit "$cur" "$next"
    cat >&2 <<EOF

Next:
  1. Read CHANGELOG.md's [$next] section. Wrong line? Reword the commit
     on dev and re-run prepare — never hand-edit the generated file.
  2. just release-pr   — pushes release/v$next and opens it -> $PRODUCTION_BRANCH; the full checks run there.
  $INTEGRATION_BRANCH stays open the whole time: cards keep merging. A fix
  for this release is a PR into release/v$next, then just release-refresh.
  Merging it (merge commit) tags v$next, publishes the one GitHub Release and
  starts BOTH TestFlight uploads (Signal and Session, marketing version $next).
EOF
}

# On a release/v* branch after a fix landed on it: regenerate the
# changelog (the fix joins this version's section) and end the branch
# with a release commit again, which is what the guard looks for.
cmd_refresh() {
    local ref v
    ref="$(git rev-parse --abbrev-ref HEAD)"
    [[ "$ref" =~ ^release/v[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "run this on the release/v* branch (on '$ref')"
    [ -z "$(git status --porcelain --untracked-files=no)" ] || die "working tree is dirty"
    git fetch --quiet --tags origin "$ref" 2>/dev/null || true
    if git rev-parse -q --verify "origin/$ref" >/dev/null; then
        git merge-base --is-ancestor "origin/$ref" HEAD \
            || die "origin/$ref has commits this checkout lacks: git pull --ff-only first"
    fi
    v="$(version_at)"
    [ "$ref" = "release/v$v" ] || die "branch $ref carries version $v"
    if [[ "$(git log -1 --format=%s)" =~ $(release_subject_re "$v") ]]; then
        note "the head is already the release commit — nothing to refresh"; return 0
    fi
    changelog_write "$v"
    git add CHANGELOG.md
    git commit --quiet --allow-empty -m "chore(release): v$v"
    note "committed: $(git log -1 --format='%h %s'). Push it: git push origin $ref"
}

# Bump the version (Cargo.toml: the one line both iOS crates follow),
# Cargo.lock, regenerate the changelog, commit `chore(release): v<next>` on
# the current branch.
release_commit() { # <cur> <next>
    local cur="$1" next="$2"
    # The one version line.
    sed -i.bak "/^\[workspace\.package\]/,/^\[/s/^version *= *\"$cur\"/version = \"$next\"/" Cargo.toml
    rm -f Cargo.toml.bak
    [ "$(version_at)" = "$next" ] || die "failed to rewrite [workspace.package] version"

    # Workspace members' entries in the lockfile follow; nothing else may
    # move. --offline first: a version bump needs no index.
    cargo update --workspace --offline 2>/dev/null || cargo update --workspace

    changelog_write "$next"

    git add Cargo.toml Cargo.lock CHANGELOG.md
    git commit --quiet -m "chore(release): v$next"
    note "committed: $(git log -1 --format='%h %s')"
}

# Write <version>'s section into CHANGELOG.md (replacing it if present),
# above every older section, which stay as released. The section holds
# exactly the commits reachable from HEAD and not from the last release
# tag — a git RANGE. git-cliff's own whole-history walk files commits
# under tags by date, and with release branches that is wrong: a card
# merged into dev while v0.2.4 was out would be listed under 0.2.4,
# which never shipped it. One section covers both apps.
changelog_write() { # <version>
    local v="$1" from sec file=CHANGELOG.md
    from="$(last_tag HEAD)"
    sec="$(mktemp)"
    # The first release creates the file with cliff.toml's header.
    [ -f "$file" ] || cliff --strip footer --tag "v$v" ${from:+"$from..HEAD"} \
        | sed '/^## \[/,$d' > "$file"
    cliff --tag "v$v" --strip all ${from:+"$from..HEAD"} > "$sec"
    grep -q "^## \[$v\]" "$sec" \
        || die "git-cliff produced no [$v] section: nothing to release since ${from:-the first commit}?"
    awk -v want="## [$v]" -v sec="$sec" '
        function emit(   n, i, l, buf) {
            n = 0; while ((getline l < sec) > 0) buf[++n] = l
            while (n > 0 && buf[n] == "") n--          # no trailing blanks
            for (i = 1; i <= n; i++) print buf[i]
            print ""; done = 1
        }
        index($0, want) == 1 { skip = 1; if (!done) emit(); next }
        skip && /^## \[/ { skip = 0 }
        skip { next }
        /^## \[/ && !done { emit() }
        { print }
        END { if (!done) emit() }
    ' "$file" > "$sec.new"
    mv "$sec.new" "$file"
    rm -f "$sec"
    grep -q "^## \[$v\]" "$file" || die "$file has no [$v] section"
}

# A hotfix when NO release branch is open: run ON a `hotfix/<name>`
# branch cut from origin/main that already carries the fix commit(s).
# Adds the patch-bump release commit the guard requires. (With a release
# branch open, the fix goes onto that branch instead: same version, one
# PR, `refresh`.) After it ships, back-merge main into dev.
cmd_hotfix() {
    local cur next ref
    ref="$(git rev-parse --abbrev-ref HEAD)"
    case "$ref" in hotfix/*) ;; *) die "run this on a hotfix/* branch cut from origin/$PRODUCTION_BRANCH (on '$ref')" ;; esac
    [ -z "$(git status --porcelain --untracked-files=no)" ] || die "working tree is dirty"
    git fetch --quiet --tags origin "$PRODUCTION_BRANCH"
    git merge-base --is-ancestor "origin/$PRODUCTION_BRANCH" HEAD \
        || die "$ref does not contain origin/$PRODUCTION_BRANCH; rebase it onto main first"
    cur="$(version_at "origin/$PRODUCTION_BRANCH")"
    next="$(bump "$cur" patch)"
    git rev-parse -q --verify "refs/tags/v$next" >/dev/null && die "tag v$next already exists"
    if git ls-remote --exit-code --heads origin "release/v$next" >/dev/null 2>&1; then
        die "release/v$next is open: put the fix on it instead (PR into release/v$next, then just release-refresh)"
    fi
    note "hotfix v$next (was $cur) on $ref"
    release_commit "$cur" "$next"
    cat >&2 <<EOF

Next:
  1. just release-pr — pushes $ref and opens it -> $PRODUCTION_BRANCH. checks + the release guard run.
  2. Merge it with "Create a merge commit". release tags v$next, publishes the Release and starts both TestFlight uploads.
  3. just release-backmerge — $PRODUCTION_BRANCH -> $INTEGRATION_BRANCH, so dev gets the fix and the bump.
EOF
}

# Push the current release/v* (or hotfix/*) branch and open its PR into
# main, with the changelog and moved git deps as the body.
cmd_pr() {
    local ref v body kind existing tag
    ref="$(git rev-parse --abbrev-ref HEAD)"
    if [[ "$ref" =~ ^release/v[0-9]+\.[0-9]+\.[0-9]+$ ]]; then kind=Release
    else
        case "$ref" in
            hotfix/*) kind=Hotfix ;;
            *) die "run this on the release/vX.Y.Z (or hotfix/*) branch (on '$ref'); just release-prepare makes one" ;;
        esac
    fi
    [ -z "$(git status --porcelain --untracked-files=no)" ] || die "working tree is dirty"
    v="$(version_at)"; tag="v$v"
    [[ "$(git log -1 --format=%s)" =~ $(release_subject_re "$v") ]] \
        || die "the head is not the release commit for $tag (just release-prepare / release-hotfix / release-refresh)"
    git fetch --quiet --tags origin "$PRODUCTION_BRANCH"
    git push --quiet origin "HEAD:refs/heads/$ref"
    existing="$(gh pr list --repo "$REPO" --head "$ref" --base "$PRODUCTION_BRANCH" --state open --json url --jq '.[0].url' 2>/dev/null || true)"
    if [ -n "$existing" ]; then
        note "pushed; the PR is already open: $existing"; return 0
    fi
    local from; from="$(last_tag "origin/$PRODUCTION_BRANCH")"
    body="$(mktemp)"
    {
        echo "$kind **$tag**: \`$ref\` → \`$PRODUCTION_BRANCH\` (source \`$(git rev-parse --short HEAD)\`)."
        echo
        echo "Merge with **Create a merge commit** (never squash or rebase): the merge"
        echo "commit's tree is the tree the checks below tested, and the \`$tag\` tag"
        echo "lands on this branch's tip, which must stay in main's history."
        echo "\`$INTEGRATION_BRANCH\` stays open meanwhile; after the release, \`just release-backmerge\`."
        echo
        echo "On merge: deploy (session-web + signal-web); release.yml tags \`$tag\`,"
        echo "publishes the one GitHub Release (Signal + Session share this version) and"
        echo "starts the REAPER suites and BOTH iOS TestFlight uploads (\`signal-ios\`,"
        echo "\`session-ios\`) on the tag, marketing version **$v**. Each writes its build"
        echo "number into the Release notes."
        echo
        local d; d="$(git_deps_moved "$from" HEAD)"
        if [ -n "$d" ]; then
            echo "### Git dependencies moved"
            # shellcheck disable=SC2086 # $d is a word list
            printf -- '- %s\n' $d
            echo
        fi
        echo "### Changelog"
        cmd_notes "$v"
    } > "$body"
    gh pr create --repo "$REPO" --base "$PRODUCTION_BRANCH" --head "$ref" \
        --title "$kind $tag" --body-file "$body"
    rm -f "$body"
}

# After a release (or hotfix) reached main: bring main back into dev with
# a merge commit, so dev carries the bump, the changelog and any fix made
# on the release branch, and the next release branch contains main.
# Idempotent: nothing to do when main is already in dev.
# What the tip of main released: the tag named by its release branch's
# `chore(release): <tag>` commit (the merge's second parent), else v<version>.
backmerge_label() {
    local s
    s="$(git log -1 --format=%s "origin/$PRODUCTION_BRANCH^2" 2>/dev/null || true)"
    if [[ "$s" =~ ^chore\(release\):\ (v[0-9]+\.[0-9]+\.[0-9]+)( |$) ]]; then
        echo "${BASH_REMATCH[1]}"
    else
        echo "v$(version_at "origin/$PRODUCTION_BRANCH")"
    fi
}

cmd_backmerge() {
    local v sha branch existing
    git fetch --quiet --tags origin "$INTEGRATION_BRANCH" "$PRODUCTION_BRANCH"
    if git merge-base --is-ancestor "origin/$PRODUCTION_BRANCH" "origin/$INTEGRATION_BRANCH"; then
        note "origin/$PRODUCTION_BRANCH is already in origin/$INTEGRATION_BRANCH — nothing to back-merge"; return 0
    fi
    sha="$(git rev-parse "origin/$PRODUCTION_BRANCH")"
    v="$(backmerge_label)"
    branch="backmerge/$v"
    existing="$(gh pr list --repo "$REPO" --head "$branch" --base "$INTEGRATION_BRANCH" --state open --json url --jq '.[0].url' 2>/dev/null || true)"
    if [ -z "$existing" ]; then
        # A branch, not main itself, as the PR head: a conflict (a card that
        # touched a workspace member's Cargo.lock entry next to its version
        # line) is resolved by merging dev into this branch, never on main.
        git push --quiet origin "$sha:refs/heads/$branch"
        existing="$(gh pr create --repo "$REPO" --base "$INTEGRATION_BRANCH" --head "$branch" \
            --title "chore(release): back-merge $v into $INTEGRATION_BRANCH" \
            --body "Brings \`$PRODUCTION_BRANCH\` ($(git rev-parse --short "$sha"), $v) back into \`$INTEGRATION_BRANCH\`: the version bump, the changelog and any fix made on the release branch. **Merge commit**, never squash: dev must contain main for the next release. Opened by \`just release-backmerge\`." | tail -1)"
    fi
    local subj="Merge $PRODUCTION_BRANCH into $INTEGRATION_BRANCH after $v"
    gh pr merge "$existing" --repo "$REPO" --merge --auto --subject "$subj" \
        || gh pr merge "$existing" --repo "$REPO" --merge --subject "$subj" \
        || note "could not enable auto-merge; merge $existing with a merge commit once its title check is green"
    note "back-merge: $existing"
    if ! git merge-tree --write-tree "origin/$INTEGRATION_BRANCH" "$sha" >/dev/null 2>&1; then
        note "it CONFLICTS: git switch $branch && git merge origin/$INTEGRATION_BRANCH, resolve (Cargo.lock: cargo update --workspace), push $branch"
    fi
}

# CI, on a pull request into main. Fails unless merging this PR would
# ship exactly the tree the checks tested, at a new version, with notes,
# and with both iOS app crates on that one version.
cmd_guard() {
    local base="${BASE_SHA:?}" head="${HEAD_SHA:?}" ref="${HEAD_REF:?}"
    local v vb merged subject cut="" ok=1 tag a cv
    fail() { echo "::error::$*"; ok=0; }

    # Bootstrap: main still takes ordinary PRs until the release flow has
    # reached it, including the one that adds this guard. That is true
    # while main has no scripts/release.sh (whether or not `dev` exists
    # yet), or while there is no `dev` at all.
    if ! git cat-file -e "$base:scripts/release.sh" 2>/dev/null; then
        echo "::notice::main has no scripts/release.sh yet — this PR introduces the release flow; release guard not enforced"
        return 0
    fi
    if ! git ls-remote --exit-code --heads origin "$INTEGRATION_BRANCH" >/dev/null 2>&1; then
        echo "::notice::no '$INTEGRATION_BRANCH' branch yet — release guard not enforced"
        return 0
    fi
    git fetch --quiet --tags origin \
        "+refs/heads/$INTEGRATION_BRANCH:refs/remotes/origin/$INTEGRATION_BRANCH" 2>/dev/null || true

    v="$(version_at "$head")"; vb="$(version_at "$base")"; tag="v$v"
    case "$ref" in
        release/v*) [ "$ref" = "release/v$v" ] \
                        || fail "branch '$ref' carries version '$v'; a release branch is named release/v<its version> (just release-prepare)" ;;
        hotfix/*) ;;
        *) fail "release PRs come from release/vX.Y.Z (just release-prepare) or hotfix/*, not '$ref'. Other PRs target '$INTEGRATION_BRANCH'." ;;
    esac

    if ! is_semver "$v"; then fail "Cargo.toml version '$v' is not X.Y.Z"
    elif ! gt "$v" "$vb"; then fail "version $v is not greater than main's $vb — cut the release with just release-prepare"
    fi
    # One version for the whole studio: Signal and Session follow the
    # workspace version (version.workspace = true), so they cannot differ.
    for a in $IOS_APPS; do
        cv="$(crate_version_at "$a" "$head")"
        [ "$cv" = "$v" ] \
            || fail "$(ios_manifest "$a") resolves to version '${cv:-none}' but the release is $v: both apps take [workspace.package] version (version.workspace = true)"
    done
    git rev-parse -q --verify "refs/tags/$tag" >/dev/null && fail "tag $tag already exists"

    git show "$head:CHANGELOG.md" 2>/dev/null | grep -q "^## \[$v\]" \
        || fail "CHANGELOG.md at the head has no [$v] section"

    subject="$(git log -1 --format=%s "$head")"
    [[ "$subject" =~ $(release_subject_re "$v") ]] \
        || fail "the head commit must be the release commit 'chore(release): $tag' (it is '$subject'). A fix landed on $ref after it: run just release-refresh on the branch and push."

    # Where the release was cut: the parent of its first release commit.
    # It must be a commit of dev — a release ships what dev integrated,
    # plus at most fixes made on the release branch itself. (Not dev's
    # HEAD: dev keeps moving while the release is out.)
    if [[ "$ref" == release/* ]]; then
        local first
        first="$(git log --reverse --format='%H %s' "$base..$head" \
            | while read -r h s; do [[ "$s" =~ $(release_subject_re "$v") ]] && { echo "$h"; break; }; done || true)"
        if [ -z "$first" ]; then
            fail "no 'chore(release): $tag' commit between main and the head"
        elif ! git rev-parse -q --verify "origin/$INTEGRATION_BRANCH" >/dev/null; then
            fail "cannot see origin/$INTEGRATION_BRANCH to check where $ref was cut"
        else
            cut="$(git rev-parse "$first^")"
            git merge-base --is-ancestor "$cut" "origin/$INTEGRATION_BRANCH" \
                || fail "$ref was not cut from $INTEGRATION_BRANCH (its base $(git rev-parse --short "$cut") is not in origin/$INTEGRATION_BRANCH). Re-cut it: just release-prepare"
        fi
    fi

    # Main must already be in the head: the back-merge of the last release
    # happened before this branch was cut (or, for a hotfix, it was cut
    # from main).
    git merge-base --is-ancestor "$base" "$head" \
        || fail "main ($(git rev-parse --short "$base")) is not in $ref: back-merge main into $INTEGRATION_BRANCH (just release-backmerge) and re-cut, or merge origin/main into $ref and run just release-refresh"

    # Tree identity: the merge commit main will get must have the head's
    # tree — so checks (which test this tree), deploy (which builds the
    # merge commit) and the tag (on the head) all name the same source.
    merged="$(git merge-tree --write-tree "$base" "$head" 2>/dev/null | head -1 || true)"
    [ "$merged" = "$(git rev-parse "$head^{tree}")" ] \
        || fail "merging into main would not reproduce the head's tree"

    {
        echo "### Release guard: $tag ($ref → main)"
        echo "- version: $vb → $v (Signal and Session: $v, one tag, one Release)"
        echo "- head: \`$(git rev-parse --short "$head")\` $subject"
        [ -n "$cut" ] && echo "- cut from $INTEGRATION_BRANCH at: \`$(git rev-parse --short "$cut")\` ($(git rev-list --count "$cut..origin/$INTEGRATION_BRANCH") commits on $INTEGRATION_BRANCH since — they ship next time)"
        [ -n "$cut" ] && echo "- fixes on the release branch: $(git log --format=%s "$cut..$head" | grep -cvE "$(release_subject_re "$v")" || true)"
        echo "- merge tree identical to head tree: $([ "$merged" = "$(git rev-parse "$head^{tree}")" ] && echo yes || echo NO)"
        echo "- on merge: $tag, its GitHub Release, the REAPER suites and the signal-ios + session-ios TestFlight uploads (marketing version $v)"
        local d; d="$(git_deps_moved "$(last_tag "$base")" "$head" | paste -sd, -)"
        echo "- git deps moved since last release: ${d:-none}"
    } >> "${GITHUB_STEP_SUMMARY:-/dev/stderr}"
    [ "$ok" = 1 ] || exit 1
    echo "release guard: ok ($tag)"
}

# The block both TestFlight uploads fill in, kept at the end of the
# release notes between these markers: one line per app.
TF_BEGIN='<!-- testflight:begin -->'
TF_END='<!-- testflight:end -->'

# The app's line in the block of a release body (empty when there is none).
tf_app_line() { # <body> <app>
    printf '%s\n' "$1" | sed -n "\\#$TF_BEGIN#,\\#$TF_END#p" | grep -F -- "- $(ios_title "$2") (" | head -1 || true
}

tf_pending_line() { # <app>
    echo "- $(ios_title "$1") (\`$(ios_bundle_id "$1")\`): pending — \`$1-ios\` builds this tag and writes its build number here"
}

# The whole block: this app's line is <newline> (when given), every other
# app's is the one already in <body>, else pending.
tf_render() { # <tag> <version> <body> [<app> <newline>]
    local a l
    echo "$TF_BEGIN"
    echo "### iOS TestFlight"
    echo "Marketing version **$2** (CFBundleShortVersionString) == this release, \`$1\`, for Signal and Session alike. One line per app, its latest upload."
    for a in $IOS_APPS; do
        if [ "$a" = "${4:-}" ]; then
            echo "${5:-}"
        else
            l="$(tf_app_line "$3" "$a")"
            echo "${l:-$(tf_pending_line "$a")}"
        fi
    done
    echo "$TF_END"
}

# CI, on a push to main (or by hand), and from the iOS workflows. Tag
# `v<version>` and publish its GitHub Release; idempotent. studio's
# product is the apps, not the two sites, so the tag does not wait for
# deploy. With no argument HEAD's workspace version names the release,
# and only a release commit (one with a changelog section) does; with a
# tag, that tag's. A tag this creates is made by GITHUB_TOKEN and starts no
# workflow, so the REAPER suites and BOTH TestFlight workflows are
# dispatched on it; a tag that already existed was pushed by someone whose
# push already started them.
publish_release() { # [tag]
    local v tag="${1:-}" target prev notes existed=0 a
    if [ -n "$tag" ]; then v="${tag#v}"; else v="$(version_at HEAD)"; tag="v$v"; fi
    is_semver "$v" || die "version '$v' is not X.Y.Z"
    if gh release view "$tag" --repo "$REPO" >/dev/null 2>&1; then
        note "release $tag already exists — nothing to do"; return 0
    fi
    # Only a release commit carries its own CHANGELOG section. A push to
    # main without one (the bootstrap PR, a docs-only merge) is not a
    # release, and must not publish a Release for an old tag.
    if ! grep -q "^## \[$v\]" CHANGELOG.md 2>/dev/null; then
        note "CHANGELOG.md has no [$v] section — not a release commit, nothing to publish"; return 0
    fi
    # Tag the release branch's tip (the merge's second parent) when it
    # carries the same tree: that commit reaches dev with the back-merge,
    # so the next changelog starts after it. A plain commit is tagged itself.
    target="$(git rev-parse HEAD)"
    if git rev-parse -q --verify HEAD^2 >/dev/null \
        && [ "$(git rev-parse 'HEAD^2^{tree}')" = "$(git rev-parse 'HEAD^{tree}')" ]; then
        target="$(git rev-parse HEAD^2)"
    fi
    if git rev-parse -q --verify "refs/tags/$tag" >/dev/null; then
        existed=1; target="$(git rev-parse "$tag^{commit}")"
        note "tag $tag exists without a release; publishing it"
    fi
    prev="$(last_tag "$target^")"

    notes="$(mktemp)"
    {
        cmd_notes "$v" || true
        local d; d="$(git_deps_moved "$prev" "$target")"
        if [ -n "$d" ]; then
            echo
            echo "### Git dependencies moved"
            # shellcheck disable=SC2086 # $d is a word list
            printf -- '- %s\n' $d
        fi
        echo
        echo "---"
        echo "Source \`$(git rev-parse --short "$target")\`, released from main \`$(git rev-parse --short HEAD)\` (site images \`sha-$(git rev-parse --short HEAD)\`)."
        [ -n "$prev" ] && echo "Full diff: https://github.com/$REPO/compare/$prev...$tag"
        echo
        tf_render "$tag" "$v" ""
    } > "$notes"
    [ -s "$notes" ] || die "no release notes for $v"

    if ! gh release create "$tag" --repo "$REPO" --target "$target" \
        --title "studio $v" --notes-file "$notes" --latest; then
        # signal-ios and session-ios both ask for the Release of a tag
        # somebody pushed by hand, and one of them is first.
        gh release view "$tag" --repo "$REPO" >/dev/null 2>&1 \
            || die "could not create the GitHub Release for $tag"
        note "release $tag was created meanwhile — nothing to do"; rm -f "$notes"; return 0
    fi
    rm -f "$notes"
    note "published https://github.com/$REPO/releases/tag/$tag"

    [ "$existed" = 0 ] || return 0
    if [ "${RELEASE_DISPATCH_REAPER:-1}" = 1 ]; then
        if gh workflow run reaper.yml --repo "$REPO" --ref "$tag"; then
            note "dispatched reaper-integration on $tag"
        else
            note "could not dispatch reaper-integration on $tag (run it by hand)"
        fi
    fi
    if [ "${RELEASE_DISPATCH_IOS:-1}" = 1 ]; then
        for a in $IOS_APPS; do
            if gh workflow run "$a-ios.yml" --repo "$REPO" --ref "$tag" -f tag="$tag"; then
                note "dispatched $a-ios on $tag (TestFlight marketing version $v)"
            else
                note "could not dispatch $a-ios on $tag (run it by hand: gh workflow run $a-ios.yml --ref $tag -f tag=$tag)"
            fi
        done
    fi
}

cmd_publish() { publish_release; }

# CI, first job of <app>-ios.yml, run in a checkout of the tag. TestFlight
# ships exactly the tag: refuse a tag that is not vX.Y.Z, an app crate
# (or the workspace) whose version is not the tag's, a tag without its
# changelog section, a commit that is not in main. Prints the marketing
# version.
cmd_ios_resolve() { # <app> <tag>
    local app="${1:-}" tag="${2:-}" v cv wv sha re
    ios_check "$app"
    re='^v[0-9]+\.[0-9]+\.[0-9]+$'
    [[ "$tag" =~ $re ]] || die "tag '$tag' does not match $re: TestFlight uploads only from a release tag"
    v="${tag#v}"
    cv="$(crate_version_at "$app")"
    [ "$cv" = "$v" ] \
        || die "$(ios_manifest "$app") says version '${cv:-none}' but the tag is $tag ($v): the marketing version is the tag's, so the crate must carry it (version.workspace = true, released with just release-prepare)"
    wv="$(version_at)"
    [ "$wv" = "$v" ] \
        || die "[workspace.package] version is '$wv' but the tag is $tag ($v): one version for Signal and Session"
    grep -q "^## \[$v\]" CHANGELOG.md 2>/dev/null \
        || die "CHANGELOG.md has no [$v] section: $tag is not a release commit"
    sha="$(git rev-parse HEAD)"
    if git rev-parse -q --verify "refs/tags/$tag" >/dev/null; then
        [ "$(git rev-parse "$tag^{commit}")" = "$sha" ] || die "this checkout ($sha) is not $tag"
    fi
    git fetch --quiet origin "$PRODUCTION_BRANCH"
    git merge-base --is-ancestor "$sha" "origin/$PRODUCTION_BRANCH" \
        || die "$tag ($(git rev-parse --short "$sha")) is not in origin/$PRODUCTION_BRANCH: only a release that reached $PRODUCTION_BRANCH goes to TestFlight"
    note "$tag: marketing version $v, commit $(git rev-parse --short "$sha"), bundle $(ios_bundle_id "$app")"
    if [ -n "${GITHUB_OUTPUT:-}" ]; then
        { echo "version=$v"; echo "sha=$sha"; echo "tag=$tag"; } >> "$GITHUB_OUTPUT"
    fi
    echo "$v"
}

cmd_ios_release() { # <tag>
    local tag="${1:-}"
    [[ "$tag" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "usage: ios-release vX.Y.Z"
    publish_release "$tag"
}

# The app's line once its build is uploaded; earlier builds of the same
# version (a re-run) stay listed at its end.
ios_record_line() { # <app> <build> <run-url> <prior line>
    local app="$1" build="$2" run="$3" prior="$4" cur old list="" line
    cur="$(sed -n 's/^.*: build \([0-9][0-9]*\),.*$/\1/p' <<<"$prior")"
    old="$(sed -n 's/^.*(earlier builds: \([0-9, ]*\))$/\1/p' <<<"$prior")"
    if [ "$cur" = "$build" ]; then echo "$prior"; return 0; fi
    [ -z "$cur" ] || list="$cur"
    [ -z "$old" ] || list="${list:+$list, }$old"
    line="- $(ios_title "$app") (\`$(ios_bundle_id "$app")\`): build $build, $(date -u +%FT%TZ)${run:+, [run]($run)}"
    [ -z "$list" ] || line="$line (earlier builds: $list)"
    echo "$line"
}

# CI, last job of <app>-ios.yml: write what was uploaded into the release
# notes, so the GitHub Release and the TestFlight build name each other.
# Signal and Session record into the SAME Release at about the same time,
# and `gh release edit` replaces the whole body, so each run re-reads the
# notes before editing and, after a short settle, checks its own line
# survived; if the other run's edit overwrote it, it goes round again.
cmd_ios_record() { # <app> <tag> <marketing> <build> [run-url]
    local app="${1:-}" tag="${2:-}" mv="${3:-}" build="${4:-}" run="${5:-}"
    local body prior line keep out tries=0 max="${RECORD_TRIES:-6}"
    ios_check "$app"
    [ "$tag" = "v$mv" ] || die "marketing version '$mv' is not the version of tag '$tag'"
    [[ "$build" =~ ^[0-9]+$ ]] || die "build number '$build' is not a number"
    while :; do
        tries=$((tries + 1))
        body="$(gh release view "$tag" --repo "$REPO" --json body --jq .body)" \
            || die "no GitHub Release for $tag (TestFlight needs one: ios-release)"
        prior="$(tf_app_line "$body" "$app")"
        if ! grep -Fq -- "): build $build," <<<"$prior"; then
            line="$(ios_record_line "$app" "$build" "$run" "$prior")"
            keep="$(printf '%s\n' "$body" | sed "\\#$TF_BEGIN#,\\#$TF_END#d" | sed -e :a -e '/^\n*$/{$d;N;ba' -e '}')"
            out="$(mktemp)"
            {
                printf '%s\n\n' "$keep"
                tf_render "$tag" "$mv" "$body" "$app" "$line"
            } > "$out"
            gh release edit "$tag" --repo "$REPO" --notes-file "$out"
            rm -f "$out"
        fi
        sleep "${RECORD_SETTLE:-4}"
        body="$(gh release view "$tag" --repo "$REPO" --json body --jq .body)" \
            || die "no GitHub Release for $tag"
        if grep -Fq -- "): build $build," <<<"$(tf_app_line "$body" "$app")"; then
            note "recorded on $tag: $app marketing $mv, build $build"
            return 0
        fi
        [ "$tries" -lt "$max" ] || die "could not record $app build $build on $tag after $tries tries: the notes kept being overwritten"
        note "the notes of $tag changed under $app's edit; trying again ($tries/$max)"
        sleep "$((RANDOM % 3 + 1))"
    done
}


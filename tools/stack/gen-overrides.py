#!/usr/bin/env python3
"""Kept here so other machines can rebuild the side-by-side stack; it runs from
the stack folder, not from this repo: copy it to <folder>/stack/ where
<folder> holds the checkouts (studio/, architect/, keyflow/, Ignition/,
session/, daw/, signal/, fts-fx/, frame/, studio-adapters/), and put Studio's
lock resolved without overrides at <folder>/stack/studio.git.lock.

Writes stack/overrides.toml: every FastTrackStudios crate a build of
Studio's distribution pulls from GitHub, redirected to the checkout beside
it in this folder. Local only; never commit the file or its paths.

    python3 -I stack/gen-overrides.py            # from Studio's Cargo.lock
    cargo --config ../stack/overrides.toml …     # in studio/, in its dev shell

A crate is looked up by name: first in the checkout of the repo the lock
says it comes from, then in any other checkout (crates that moved repos:
Ignition still asks the studio repo for `daw`, which lives in daw/ now).
"""
import json
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPOS = ["architect", "studio", "keyflow", "Ignition", "session", "daw",
         "signal", "fts-fx", "frame", "studio-adapters"]
# Studio's lock as resolved WITHOUT overrides: a lock written under them
# names paths, not repos. Refresh it after changing a manifest:
#   (cd studio && git checkout Cargo.lock && cargo metadata >/dev/null && cp Cargo.lock ../stack/studio.git.lock)
LOCK = ROOT / "stack" / "studio.git.lock"
OUT = ROOT / "stack" / "overrides.toml"


def members(repo: str) -> dict[str, Path]:
    out = subprocess.run(
        ["cargo", "metadata", "--no-deps", "--format-version", "1", "--offline"],
        cwd=ROOT / repo, check=True, capture_output=True, text=True).stdout
    return {p["name"]: Path(p["manifest_path"]).parent for p in json.loads(out)["packages"]}


def main() -> int:
    index = {r: members(r) for r in REPOS}
    by_lower = {r.lower(): r for r in REPOS}
    wanted: dict[str, set[str]] = {}  # source URL (no query) -> crate names
    for pkg in tomllib.loads(LOCK.read_text())["package"]:
        src = pkg.get("source", "")
        m = re.match(r"git\+(https://(?:www\.)?github\.com/FastTrackStudios/([^?#/]+?)(?:\.git)?)(\.git)?[?#]", src)
        if m and m.group(2).lower() in by_lower:
            wanted.setdefault(m.group(2).lower(), set()).add(pkg["name"])
    lines = [f"# GENERATED by {Path(__file__).name}. Local only: never commit this file or its paths.", ""]
    missing = []
    for key in sorted(wanted):
        repo = by_lower[key]
        rows = []
        for name in sorted(wanted[key]):
            path = index[repo].get(name)
            if path is None:
                # A crate its repo no longer holds (Ignition asks the studio
                # repo, at an old revision, for `daw`, `ableton`, `dsp`…):
                # left on that revision. The crate of that name elsewhere
                # has moved on (ableton lost `time_signature_automation`).
                missing.append(f"{repo}/{name}")
                continue
            rows.append(f'{name} = {{ path = "{path}" }}')
        for url in (f"https://github.com/FastTrackStudios/{repo}",
                    f"https://www.github.com/FastTrackStudios/{repo}"):
            lines.append(f'[patch."{url}"]')
            lines.extend(rows)
            lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"{OUT}: {sum(len(v) for v in wanted.values())} crates over {len(wanted)} repos")
    for m in missing:
        print("  not redirected:", m, file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())

/// A stroked icon at `size` px with a `w` stroke.
#[component]
pub fn Icon(name: I, #[props(default = 20)] size: u32, #[props(default = 1.8)] w: f32) -> Element {
    rsx! {
        svg {
            width: "{size}",
            height: "{size}",
            view_box: "0 0 24 24",
            fill: "none",
            stroke: "currentColor",
            stroke_width: "{w}",
            stroke_linecap: "round",
            stroke_linejoin: "round",
            dangerous_inner_html: name.body(),
        }
    }
}

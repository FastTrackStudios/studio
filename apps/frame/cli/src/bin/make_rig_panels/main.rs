/// The rig row's box in `rig_shot`'s 1600 × 1000 window.
pub const ORIGIN: (f64, f64) = (285.0, 95.0);
pub const ROW: (f64, f64) = (1225.0, 535.0);

/// The rig's tempo (design profile).
pub const BPM: f64 = 149.0;

/// When in the design instrument's life the row is shown, s.
pub const T: f32 = 1.28;

// ── signal's design instrument (`signal-guitar/src/design.rs`) ──────────

const PLUCK_EVERY: f32 = 1.4;

fn envelope(t: f32) -> f32 {
    let phase = (t / PLUCK_EVERY).fract().abs();
    let since = phase * PLUCK_EVERY;
    let attack = (since / 0.008).min(1.0);
    let decay = (-since / 0.6).exp();
    let velocity = 0.55 + 0.45 * ((t / (PLUCK_EVERY * 3.0)) * TAU).sin().abs();
    (0.04 + 0.92 * attack * decay * velocity).clamp(0.0, 1.0)
}

fn gain_reduction_db(env: f32) -> f32 {
    let db = 20.0 * env.max(1e-5).log10();
    let over = db + 18.0;
    if over <= 0.0 { 0.0 } else { over * (1.0 - 1.0 / 4.0) }
}

fn spectrum(t: f32, bins: usize) -> Vec<f32> {
    let env = envelope(t);
    let level = 20.0 * env.max(1e-5).log10();
    (0..bins)
        .map(|i| {
            let frac = if bins > 1 { i as f32 / (bins - 1) as f32 } else { 0.0 };
            let hz = 20.0 * 1000f32.powf(frac);
            let roll = if hz > 4000.0 { -24.0 * (hz / 4000.0).log10() } else { 0.0 };
            let mut shape = -6.0 * ((hz / 120.0).log10()).abs();
            for n in 1..=6 {
                let partial = 82.41 * n as f32;
                let width = partial * 0.06;
                let d = (hz - partial) / width;
                shape += 14.0 * (-d * d).exp() / n as f32;
            }
            let shimmer = 1.5 * ((t * 3.0 + frac * 20.0) * TAU).sin();
            (level + roll + shape + shimmer - 6.0).clamp(-90.0, 0.0)
        })
        .collect()
}

fn traces(t: f32, n: usize) -> (Vec<f32>, Vec<f32>) {
    let span = 4.0;
    let step = span / n.max(1) as f32;
    let mut input = Vec::with_capacity(n);
    let mut reduction = Vec::with_capacity(n);
    for i in 0..n {
        let at = t - (n - 1 - i) as f32 * step;
        let env = envelope(at.max(0.0));
        input.push(env);
        reduction.push((gain_reduction_db(env) / 24.0).clamp(0.0, 1.0));
    }
    (input, reduction)
}

// ── the rig view's treatment (`signal-guitar-ui/src/state.rs`) ──────────

/// The analyser as the rig shows it at `t`: every ~30 Hz spectrum event
/// since the start, 3-tap smoothed, instant attack, −1.3 dB an event.
fn rig_spectrum(t: f32) -> Vec<f32> {
    let mut prev: Vec<f32> = Vec::new();
    let events = (t * 30.0).floor() as usize;
    for k in 0..=events {
        let bins = spectrum(k as f32 / 30.0, 96);
        let n = bins.len();
        prev = (0..n)
            .map(|i| {
                let (a, b, c) = (bins[i.saturating_sub(1)], bins[i], bins[(i + 1).min(n - 1)]);
                let fresh = (2.0f32.mul_add(b, a) + c) / 4.0;
                let fallen = prev.get(i).copied().unwrap_or(-90.0) - 1.3;
                fresh.max(fallen).max(-90.0)
            })
            .collect();
    }
    prev
}

fn smooth3(v: &[f32]) -> Vec<f32> {
    let n = v.len();
    (0..n).map(|k| (2.0f32.mul_add(v[k], v[k.saturating_sub(1)]) + v[(k + 1).min(n - 1)]) / 4.0).collect()
}

/// The feeds at `t`, as `id=v,v,…` lines (`render_surface --stream-file`).
#[must_use]
pub fn feeds(t: f32) -> Vec<(String, Vec<f64>)> {
    let (input, gr) = traces(t, 120);
    let (input, gr) = (smooth3(&input), smooth3(&gr));
    // The compressor surface's display: input linear → dB over its 60 dB,
    // the GR ring (0..1 of 30 dB) onto the same 60. The component reads
    // dB (input) and dB ≤ 0 (reduction) and maps them the same way.
    let in_db: Vec<f64> = input.iter().map(|&p| if p <= 0.0 { -120.0 } else { f64::from(20.0 * p.log10()) }).collect();
    let gr_db: Vec<f64> = gr.iter().map(|&g| -f64::from(g) * 30.0).collect();
    let now = f64::from(20.0 * envelope(t).max(1e-5).log10());
    let spectrum: Vec<f64> = rig_spectrum(t).into_iter().map(f64::from).collect();
    vec![
        ("comp/in".into(), vec![now]),
        // The design rig reports no detector reduction (`gr_db: 0.0`).
        ("comp/gr".into(), vec![0.0]),
        ("comp/in_history".into(), in_db),
        ("comp/gr_history".into(), gr_db),
        // The rig hands the same analyser to the glow (raw dBFS) and to the
        // vector pass as the graph's PRE layer (its tap is ahead of the EQ).
        ("eq/spectrum".into(), spectrum.clone()),
        ("eq/spectrum_pre".into(), spectrum),
    ]
}

// ── the catalog: the design rig's blocks ────────────────────────────────

fn set_real(params: &mut [ParamInfo], addr: &str, v: f64) {
    if let Some(p) = params.iter_mut().find(|p| p.addr.0 == addr) {
        p.default = match &p.kind {
            ParamKind::Choice { options } => v / (options.len().max(2) - 1) as f64,
            ParamKind::Toggle => v,
            _ => p.range.to_normalized(v),
        };
    }
}

/// Seconds a Hall rings at `decay` (reverb-dsp's `decay_seconds`: 0.4 · 75^d).
fn hall_seconds(decay: f64) -> f64 {
    0.4 * 75f64.powf(decay)
}

/// A delay lane's `mix`: the block's level as gain (`level_gain`).
fn level_gain(db: f64) -> f64 {
    10f64.powf(db / 20.0)
}

#[must_use]
pub fn catalog() -> Catalog {
    let mut params = Vec::new();
    let (mut comp, _) = viz::lit_catalog::comp_scope("comp", 120);
    set_real(&mut comp, "comp/threshold", -30.0);
    set_real(&mut comp, "comp/ratio", 4.0);
    set_real(&mut comp, "comp/knee", 6.0);
    params.extend(comp);

    let mut eq = viz::catalog::eq_params("eq", 24);
    eq.extend(viz::catalog::eq_view_params("eq"));
    // `Amp EQ`: a 12 dB/oct low cut at 80 Hz, bells at 212, 420 (+1.6),
    // 1.4 k and 5.5 k.
    for (n, f, g, shape) in [(1, 80.0, 0.0, 3.0), (2, 212.0, 0.0, 0.0), (3, 420.09, 1.6225, 0.0), (4, 1400.0, 0.0, 0.0), (5, 5500.0, 0.0, 0.0)] {
        set_real(&mut eq, &format!("eq/b{n}_used"), 1.0);
        set_real(&mut eq, &format!("eq/b{n}_on"), 1.0);
        set_real(&mut eq, &format!("eq/b{n}_freq"), f);
        set_real(&mut eq, &format!("eq/b{n}_gain"), g);
        set_real(&mut eq, &format!("eq/b{n}_q"), 0.707);
        set_real(&mut eq, &format!("eq/b{n}_shape"), shape);
        set_real(&mut eq, &format!("eq/b{n}_slope"), 2.0);
    }
    // The rig's EQ opens at ±12 dB.
    set_real(&mut eq, "eq/range", 2.0);
    set_real(&mut eq, "eq/show_post", 0.0);
    params.extend(eq);

    // Modulation: `Chorus` (1 Hz, depth 0.5, mix 1); Motion: `Tremolo`
    // (4 Hz, depth 0.5, mix 1).
    for (ns, engine, rate) in [("mod", 0.0, 1.0), ("motion", 3.0, 4.0)] {
        let mut m = viz::lit_catalog::mod_params(ns);
        set_real(&mut m, &format!("{ns}/rate"), rate);
        set_real(&mut m, &format!("{ns}/depth"), 0.5);
        set_real(&mut m, &format!("{ns}/mix"), 1.0);
        set_real(&mut m, &format!("{ns}/engine"), engine);
        params.extend(m);
    }

    // `DLY 1`: Tape, ¼ both sides, 223.6 ms, fb 0.28, −9.1 dB.
    // `DLY 2`: Shimmer (Pitch), dotted ⅛ both sides, 600 ms, fb 0.62, −20 dB.
    for (ns, time, fb, level, div, family) in [("dly1", 223.6, 0.28, -9.118_637, 0.0, 1.0), ("dly2", 600.0, 0.62, -20.0, 1.0, 3.0)] {
        let mut d = viz::lit_catalog::delay_params(ns);
        set_real(&mut d, &format!("{ns}/time"), time);
        set_real(&mut d, &format!("{ns}/feedback"), fb);
        set_real(&mut d, &format!("{ns}/mix"), level_gain(level).clamp(0.02, 1.0));
        set_real(&mut d, &format!("{ns}/tap_div_l"), div);
        set_real(&mut d, &format!("{ns}/tap_div_r"), div);
        set_real(&mut d, &format!("{ns}/family"), family);
        set_real(&mut d, &format!("{ns}/bpm"), BPM);
        params.extend(d);
    }

    // `VERB 1` / `VERB 2`: Halls at decay 0.42 / 0.85 (2.45 s / 15.7 s),
    // size 0.45 / 0.92, −22 / −20 dB, no pre-delay; the lane reads `damp`,
    // which the block does not have (it is `damping`), so 0.
    for (ns, decay, size, level) in [("verb1", 0.42, 0.45, -22.0), ("verb2", 0.85, 0.92, -20.0)] {
        let mut r = viz::lit_catalog::reverb_params(ns);
        set_real(&mut r, &format!("{ns}/decay"), hall_seconds(decay));
        set_real(&mut r, &format!("{ns}/predelay"), 0.0);
        set_real(&mut r, &format!("{ns}/density"), size);
        set_real(&mut r, &format!("{ns}/damp"), 0.0);
        set_real(&mut r, &format!("{ns}/mix"), level_gain(level).clamp(0.02, 1.0).max(0.15));
        set_real(&mut r, &format!("{ns}/family"), 1.0);
        set_real(&mut r, &format!("{ns}/bpm"), BPM);
        params.extend(r);
    }

    let mut streams = viz::catalog::comp_streams("comp", 120);
    streams.push(FeedInfo::new("eq/spectrum", "Spectrum", FeedKind::spectrum(96)));
    streams.push(FeedInfo::new("eq/spectrum_pre", "Spectrum (pre)", FeedKind::spectrum(96)));
    streams.push(FeedInfo::new("eq/sidechain", "Sidechain", FeedKind::spectrum(96)));
    Catalog { id: "rig-panels".into(), version: 1, params, actions: Vec::new(), streams, collections: Vec::new() }
}


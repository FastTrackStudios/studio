//! Write `examples/surfaces/13-rig-panels.frame`: signal's guitar-rig control
//! row (compressor, EQ, modulation + motion, the two delays, the two
//! reverbs) rebuilt from frame's lit visualizers at the rig's own pixel
//! sizes, with the catalog and the feeds its design mode plays.
//!
//! ```text
//! make_rig_panels [--out-dir examples/surfaces] [--time 1.28]
//! render_surface --markup examples/surfaces/13-rig-panels.frame \
//!     --catalog examples/surfaces/rig-panels.catalog.json \
//!     --stream-file examples/surfaces/rig-panels.feeds --time 1.28 --out row.png
//! ```
//!
//! The surface is the rig's row as `rig_shot` lays it out in a 1600 × 1000
//! window, cut at (285, 95): every panel at the offset and size Blitz gives
//! it, so a crop of the rig and the same crop of this line up pixel for
//! pixel. The params are the design-mode rig's blocks (`Pre Comp`, `Amp EQ`,
//! `Chorus`, `Tremolo`, `DLY 1`/`DLY 2`, `VERB 1`/`VERB 2` at 149 BPM) and
//! the feeds are signal's design instrument (`signal-guitar::design`: a
//! pluck every 1.4 s, its spectrum and compressor traces) put through the
//! rig view's own treatment (the analyser's ballistics and 3-tap smooth,
//! the trace smooth, the compressor surface's 60 dB display).
//!
//! The visualizers are frame's kit components (`viz.comp_scope`,
//! `viz.eq_graph`, `viz.mod_lfo`, `viz.delay_taps`, `viz.reverb_space`).
//! Everything around them — panel grounds and rules, headers, pickers,
//! buttons, knobs, readouts, icons — is `chrome.rs`, generated by
//! `chrome.py` from `rig_shot`'s DOM (every element's box and computed
//! style, every text run as outlines in the fonts Blitz used, every inline
//! SVG) and painted in the rig's own order, with the widgets slotted in
//! where the rig mounts them. The knobs are drawn at the rig's values, not
//! bound: the row is a picture of the rig to hold frame's visualizers
//! against.
//!
//! Each rig widget keeps its own animation clock (born when it mounted), so
//! a still of the rig catches its lanes at different phases; one `--time`
//! can match one lane at a time.

